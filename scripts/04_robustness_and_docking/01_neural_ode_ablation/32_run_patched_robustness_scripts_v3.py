def validate_manifest(df: pd.DataFrame) -> None:
    required = {
        "phase_order", "phase", "run_id", "script_language", "source_script",
        "overrides_json", "heavy",
    }
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(f"Manifest missing required columns: {missing}")
    if df["run_id"].duplicated().any():
        duplicates = df.loc[df["run_id"].duplicated(keep=False), "run_id"].tolist()
        raise ValueError(f"Manifest contains duplicate run_id values: {duplicates}")


def select_manifest_rows(df: pd.DataFrame, mode: str, targets: Sequence[str], skip_heavy: bool) -> pd.DataFrame:
    mode = mode.strip().lower()
    targets_set = {str(x) for x in targets}

    if mode == "all":
        selected = df.copy()
    elif mode == "phases":
        selected = df[df["phase"].astype(str).isin(targets_set)].copy()
    elif mode == "run_ids":
        selected = df[df["run_id"].astype(str).isin(targets_set)].copy()
    else:
        raise ValueError("CONFIG['run_mode'] must be 'run_ids', 'phases', or 'all'.")

    if skip_heavy:
        selected = selected[~selected["heavy"].map(parse_bool)].copy()

    selected = selected.sort_values(["phase_order", "phase", "run_id"]).reset_index(drop=True)
    if selected.empty:
        available_phases = sorted(df["phase"].astype(str).unique())
        available_runs = sorted(df["run_id"].astype(str).unique())
        raise ValueError(
            "No manifest rows matched the current selection.\n"
            f"run_mode={mode!r}, run_targets={list(targets)!r}\n"
            f"Available phases: {available_phases}\n"
            f"Available run_ids: {available_runs}"
        )
    return selected


