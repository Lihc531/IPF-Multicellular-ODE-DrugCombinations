def find_script(source_script: str, roots: Sequence[Path]) -> Tuple[Optional[Path], List[Path]]:
    basename = Path(source_script).name
    hits: List[Path] = []

    for root in roots:
        direct = root / source_script
        if direct.is_file():
            hits.append(direct.resolve())
        direct_basename = root / basename
        if direct_basename.is_file():
            hits.append(direct_basename.resolve())
        if root.is_dir():
            hits.extend(p.resolve() for p in root.rglob(basename) if p.is_file())

    unique_hits = sorted(set(hits), key=lambda p: (len(p.parts), len(str(p)), str(p).lower()))
    return (unique_hits[0] if unique_hits else None), unique_hits


# ============================================================================
# 4. SAFE R ASSIGNMENT PATCHING
# ============================================================================


def _find_r_assignment_span(text: str, variable: str) -> Optional[Tuple[int, int, str]]:
    """Find the complete first R assignment for a variable.

    Handles both single-line assignments and multi-line expressions such as:

        out_dir <- file.path(
          project_dir,
          "results"
        )

    Returns (statement_start, statement_end_excluding_newline, old_statement).
    """

    pattern = re.compile(
        rf"(?m)^(?P<indent>[ \t]*){re.escape(variable)}[ \t]*(?P<op><-|=(?!=))[ \t]*"
    )
    match = pattern.search(text)
    if match is None:
        return None

    statement_start = match.start()
    i = match.end()
    n = len(text)

    paren = bracket = brace = 0
    quote: Optional[str] = None
    escaped = False
    in_comment = False

    while i < n:
        ch = text[i]

        if in_comment:
            if ch == "\n":
                in_comment = False
                if paren == 0 and bracket == 0 and brace == 0 and quote is None:
                    return statement_start, i, text[statement_start:i]
            i += 1
            continue

        if quote is not None:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = None
            i += 1
            continue

        if ch in {'"', "'", "`"}:
            quote = ch
        elif ch == "#":
            in_comment = True
        elif ch == "(":
            paren += 1
        elif ch == ")":
            paren = max(0, paren - 1)
        elif ch == "[":
            bracket += 1
        elif ch == "]":
            bracket = max(0, bracket - 1)
        elif ch == "{":
            brace += 1
        elif ch == "}":
            brace = max(0, brace - 1)
        elif ch == "\n" and paren == 0 and bracket == 0 and brace == 0:
            return statement_start, i, text[statement_start:i]
        elif ch == ";" and paren == 0 and bracket == 0 and brace == 0:
            return statement_start, i, text[statement_start:i]
        i += 1

    return statement_start, n, text[statement_start:n]


def has_r_assignment(text: str, variable: str) -> bool:
    return _find_r_assignment_span(text, variable) is not None


def patch_r_assignment(text: str, variable: str, value: Any, source: str) -> Tuple[str, PatchRecord]:
    span = _find_r_assignment_span(text, variable)
    if span is None:
        raise KeyError(f"R assignment not found: {variable}")
    start, end, old_statement = span
    indent_match = re.match(r"[ \t]*", old_statement)
    indent = indent_match.group(0) if indent_match else ""
    new_statement = f"{indent}{variable} <- {r_literal(value)}"
    patched = text[:start] + new_statement + text[end:]
    return patched, PatchRecord("R", variable, old_statement, new_statement, source)


def patch_r_script(
    text: str,
    manifest_assignments: Mapping[str, Any],
    input_assignments: Mapping[str, Path],
    output_dir: Path,
    force_isolated_output: bool,
) -> Tuple[str, List[PatchRecord], List[str]]:
    patched = text
    records: List[PatchRecord] = []
    warnings: List[str] = []

    assignments = dict(manifest_assignments)
    if force_isolated_output and has_r_assignment(patched, "out_dir"):
        assignments["out_dir"] = output_dir
    if force_isolated_output and has_r_assignment(patched, "outdir"):
        assignments["outdir"] = output_dir

    for variable, value in assignments.items():
        try:
            patched, record = patch_r_assignment(patched, variable, value, "manifest")
            records.append(record)
        except KeyError as exc:
            raise RuntimeError(str(exc)) from exc

    for variable, path in input_assignments.items():
        if not has_r_assignment(patched, variable):
            warnings.append(f"Input override variable not present in script: {variable}")
            continue
        patched, record = patch_r_assignment(patched, variable, path, "input_resolver")
        records.append(record)

    return patched, records, warnings


