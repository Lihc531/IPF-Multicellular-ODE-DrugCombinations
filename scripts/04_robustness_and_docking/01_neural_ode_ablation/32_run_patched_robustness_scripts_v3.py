# 5. SAFE PYTHON CONFIG PATCHING USING AST
# ============================================================================


def _python_position_to_offset(text: str, lineno: int, col_offset_bytes: int) -> int:
    lines = text.splitlines(keepends=True)
    base = sum(len(line) for line in lines[: lineno - 1])
    line = lines[lineno - 1]
    prefix = line.encode("utf-8")[:col_offset_bytes].decode("utf-8", errors="ignore")
    return base + len(prefix)


def _find_top_level_config_dict(tree: ast.AST) -> Tuple[str, ast.Dict]:
    candidates: List[Tuple[str, ast.Dict]] = []
    for node in getattr(tree, "body", []):
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Dict):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in {"CONFIG", "BASE_CONFIG"}:
                    candidates.append((target.id, node.value))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and isinstance(node.value, ast.Dict):
            if node.target.id in {"CONFIG", "BASE_CONFIG"}:
                candidates.append((node.target.id, node.value))
    if not candidates:
        raise RuntimeError("No top-level CONFIG or BASE_CONFIG dictionary found in Python script.")
    # Prefer CONFIG, otherwise BASE_CONFIG.
    candidates.sort(key=lambda x: (0 if x[0] == "CONFIG" else 1))
    return candidates[0]


def _dict_key_map(dict_node: ast.Dict) -> Dict[str, ast.AST]:
    result: Dict[str, ast.AST] = {}
    for key_node, value_node in zip(dict_node.keys, dict_node.values):
        if isinstance(key_node, ast.Constant) and isinstance(key_node.value, str):
            result[key_node.value] = value_node
    return result


def patch_python_config(
    text: str,
    assignments: Mapping[str, Any],
    output_dir: Path,
    force_isolated_output: bool,
) -> Tuple[str, List[PatchRecord], List[str]]:
    tree = ast.parse(text)
    config_name, config_dict = _find_top_level_config_dict(tree)
    key_map = _dict_key_map(config_dict)

    effective = dict(assignments)
    if force_isolated_output and "outdir" in key_map:
        effective["outdir"] = str(output_dir)
    elif force_isolated_output and "output_dir" in key_map:
        effective["output_dir"] = str(output_dir)

    replacements: List[Tuple[int, int, str, PatchRecord]] = []
    warnings: List[str] = []

    for key, value in effective.items():
        node = key_map.get(key)
        if node is None:
            raise RuntimeError(f"Python {config_name} key not found: {key}")
        if not all(hasattr(node, attr) for attr in ("lineno", "col_offset", "end_lineno", "end_col_offset")):
            raise RuntimeError(f"Python AST does not provide source location for key: {key}")

        start = _python_position_to_offset(text, node.lineno, node.col_offset)
        end = _python_position_to_offset(text, node.end_lineno, node.end_col_offset)
        old_text = text[start:end]
        literal = python_literal(value)
        if "\n" in literal:
            indent = " " * node.col_offset
            parts = literal.splitlines()
            literal = parts[0] + "\n" + "\n".join(indent + line for line in parts[1:])
        record = PatchRecord("PY", key, old_text, literal, f"{config_name}")
        replacements.append((start, end, literal, record))

    patched = text
    records: List[PatchRecord] = []
    for start, end, literal, record in sorted(replacements, key=lambda x: x[0], reverse=True):
        patched = patched[:start] + literal + patched[end:]
        records.append(record)
    records.reverse()

    # Final syntax validation at patch stage.
    ast.parse(patched)
    return patched, records, warnings


