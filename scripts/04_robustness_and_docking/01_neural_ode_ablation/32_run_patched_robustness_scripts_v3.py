def validate_r_script(script: Path, rscript_bin: Path, cwd: Path, log_path: Path) -> Tuple[bool, str]:
    expr = f"parse(file={json.dumps(path_for_r(script), ensure_ascii=False)})"
    proc = subprocess.run(
        [str(rscript_bin), "--vanilla", "-e", expr],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        errors="replace",
    )
    content = (proc.stdout or "") + (proc.stderr or "")
    log_path.write_text(content, encoding="utf-8", errors="ignore")
    return proc.returncode == 0, content


def validate_python_script(script: Path, python_bin: Path, cwd: Path, log_path: Path) -> Tuple[bool, str]:
    proc = subprocess.run(
        [str(python_bin), "-m", "py_compile", str(script)],
        cwd=str(cwd),
        capture_output=True,
        text=True,
        errors="replace",
    )
    content = (proc.stdout or "") + (proc.stderr or "")
    log_path.write_text(content, encoding="utf-8", errors="ignore")
    return proc.returncode == 0, content


def _pump_stream(stream, log_handle, prefix: str) -> None:
    try:
        for line in iter(stream.readline, ""):
            log_handle.write(line)
            log_handle.flush()
            print(f"{prefix}{line}", end="")
    finally:
        stream.close()


def run_process_streaming(
    cmd: Sequence[str],
    cwd: Path,
    env: Mapping[str, str],
    stdout_log: Path,
    stderr_log: Path,
) -> int:
    stdout_log.parent.mkdir(parents=True, exist_ok=True)
    with stdout_log.open("w", encoding="utf-8", errors="ignore") as out_handle, \
            stderr_log.open("w", encoding="utf-8", errors="ignore") as err_handle:
        proc = subprocess.Popen(
            list(cmd),
            cwd=str(cwd),
            env=dict(env),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            errors="replace",
            bufsize=1,
        )
        assert proc.stdout is not None
        assert proc.stderr is not None
        t_out = threading.Thread(target=_pump_stream, args=(proc.stdout, out_handle, ""), daemon=True)
        t_err = threading.Thread(target=_pump_stream, args=(proc.stderr, err_handle, ""), daemon=True)
        t_out.start()
        t_err.start()
        returncode = proc.wait()
        t_out.join()
        t_err.join()
        return returncode


