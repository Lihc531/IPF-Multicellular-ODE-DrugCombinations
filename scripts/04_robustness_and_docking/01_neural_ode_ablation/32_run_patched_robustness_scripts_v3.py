def parse_optional_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(add_help=True)
    parser.add_argument("--manifest", default=None)
    parser.add_argument("--mode", choices=["run_ids", "phases", "all"], default=None)
    parser.add_argument("--target", action="append", default=None)
    parser.add_argument("--execute", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def main() -> None:
    config = deepcopy(CONFIG)
    args = parse_optional_args()
    if args.manifest:
        config["manifest"] = args.manifest
    if args.mode:
        config["run_mode"] = args.mode
    if args.target is not None:
        config["run_targets"] = args.target
    if args.execute:
        config["execute"] = True
    if args.dry_run:
        config["execute"] = False

    manifest_path = Path(config["manifest"])
    ensure_file(manifest_path, "Manifest")
    ensure_dir(Path(config["r_project_root"]), "R project root")
    ensure_dir(Path(config["python_project_root"]), "Python project root")

    manifest = pd.read_csv(manifest_path, low_memory=False)
    validate_manifest(manifest)
    selected = select_manifest_rows(
        manifest,
        str(config["run_mode"]),
        list(config.get("run_targets", [])),
        bool(config.get("skip_heavy", False)),
    )

    print("\n" + "=" * 78)
    print("ROBUSTNESS RUNNER V3")
    print("=" * 78)
    print(f"Manifest: {manifest_path}")
    print(f"Mode: {config['run_mode']}")
    print(f"Targets: {config.get('run_targets', [])}")
    print(f"Execute: {config['execute']}")
    print("\nMatched runs:")
    print(selected[["phase_order", "phase", "run_id", "script_language", "source_script"]].to_string(index=False))
    print("=" * 78)

    results: List[RunResult] = []
    work_root = Path(config["work_root"])
    work_root.mkdir(parents=True, exist_ok=True)

    for _, row in selected.iterrows():
        print("\n" + "=" * 78)
        print(f"运行: {row['run_id']}")
        print(f"阶段: {row['phase']}")
        print("=" * 78)
        try:
            result = execute_one(row, config)
        except Exception as exc:
            result = RunResult(
                str(row["run_id"]), str(row["phase"]), "runner_error", None,
                "", "", "", str(row["source_script"]), 0, f"{type(exc).__name__}: {exc}"
            )
            print(f"[ERROR] {result.message}")
        results.append(result)
        print(f"状态: {result.status}")
        print(f"返回码: {result.returncode}")
        print(f"输出文件数: {result.n_output_files}")
        if result.message:
            print(f"说明: {result.message}")

        if result.status not in {"ok", "prepared_dry_run", "skipped_successful"} and config.get("stop_on_error", True):
            print("[STOP] stop_on_error=True，停止后续任务。")
            break

    summary = pd.DataFrame([r.__dict__ for r in results])
    summary_path = work_root / "00_v3_run_summary.csv"
    summary.to_csv(summary_path, index=False, encoding="utf-8-sig")
    json_dump(work_root / "00_v3_run_summary.json", {
        "created_at": now_iso(),
        "config": config,
        "results": [r.__dict__ for r in results],
    })

    print("\n" + "=" * 78)
    print("V3 运行结束")
    print(f"汇总文件: {summary_path}")
    if not summary.empty:
        print(summary[["run_id", "phase", "status", "returncode", "n_output_files"]].to_string(index=False))
    print("=" * 78)

    failed = [r for r in results if r.status not in {"ok", "prepared_dry_run", "skipped_successful"}]
    if failed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
