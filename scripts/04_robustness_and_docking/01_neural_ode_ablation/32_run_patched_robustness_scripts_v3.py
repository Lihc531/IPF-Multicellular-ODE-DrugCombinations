def resolve_r_inputs(phase: str, config: Mapping[str, Any]) -> Tuple[Dict[str, Path], Dict[str, Any]]:
    registry = build_r_input_candidates(config)
    phase_registry = registry.get(phase, {})
    resolved: Dict[str, Path] = {}
    report: Dict[str, Any] = {}

    for variable, spec in phase_registry.items():
        candidates = [Path(p) for p in spec.get("candidates", [])]
        existing = next((p for p in candidates if p.is_file()), None)
        report[variable] = {
            "required": bool(spec.get("required", True)),
            "candidates": [str(p) for p in candidates],
            "resolved": str(existing) if existing else None,
        }
        if existing is not None:
            resolved[variable] = existing
        elif spec.get("required", True):
            options = "\n  - ".join(str(p) for p in candidates)
            raise FileNotFoundError(
                f"Required input for phase '{phase}' was not found: {variable}\n"
                f"Checked:\n  - {options}"
            )

    return resolved, report


