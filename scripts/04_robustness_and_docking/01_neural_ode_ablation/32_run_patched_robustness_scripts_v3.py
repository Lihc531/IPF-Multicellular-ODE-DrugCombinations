def now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return False
    return str(value).strip().lower() in {"1", "true", "yes", "y", "t"}


def ensure_file(path: Path, label: str) -> None:
    if not path.is_file():
        raise FileNotFoundError(f"{label} not found: {path}")


def ensure_dir(path: Path, label: str) -> None:
    if not path.is_dir():
        raise NotADirectoryError(f"{label} not found: {path}")


def json_dump(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2, default=str), encoding="utf-8")


def path_for_r(path: Path | str) -> str:
    return str(path).replace("\\", "/")


def python_literal(value: Any) -> str:
    if isinstance(value, Path):
        value = str(value)
    if isinstance(value, dict):
        return pprint.pformat(value, sort_dicts=False, width=100)
    return repr(value)


def r_literal(value: Any) -> str:
    if isinstance(value, Path):
        value = path_for_r(value)
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        stripped = value.strip()
        if re.fullmatch(r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?", stripped):
            return stripped
        if stripped in {"TRUE", "FALSE", "NULL", "NA", "NA_real_", "NA_integer_"}:
            return stripped
        # Preserve explicit R expressions from the manifest when requested.
        if stripped.startswith(("file.path(", "c(", "list(", "paste0(", "Sys.getenv(", "normalizePath(")):
            return stripped
        return json.dumps(path_for_r(stripped), ensure_ascii=False)
    return str(value)


def count_output_files(output_dir: Path) -> int:
    if not output_dir.exists():
        return 0
    return sum(1 for p in output_dir.rglob("*") if p.is_file())


