def prepare_environment(language: str, source_script: Path, run_dir: Path, output_dir: Path, phase: str, run_id: str) -> Dict[str, str]:
    env = os.environ.copy()
    env["ROBUSTNESS_RUN_ID"] = run_id
    env["ROBUSTNESS_PHASE"] = phase
    env["ROBUSTNESS_RUN_DIR"] = str(run_dir)
    env["ROBUSTNESS_OUT_DIR"] = str(output_dir)

    if language in {"PY", "PYTHON"}:
        existing = env.get("PYTHONPATH", "")
        additions = [str(source_script.parent)]
        env["PYTHONPATH"] = os.pathsep.join(additions + ([existing] if existing else []))
    return env


def execute_one(row: pd.Series, config: Mapping[str, Any]) -> RunResult:
    run_id = str(row["run_id"])
    phase = str(row["phase"])
    language = str(row["script_language"]).upper()
    source_name = str(row["source_script"])
    phase_order = int(row["phase_order"])

    work_root = Path(config["work_root"])
    run_dir = work_root / f"{phase_order:02d}_{phase}" / run_id
    output_dir = run_dir / str(config["output_subdir"])
    logs_dir = run_dir / "logs"
    metadata_dir = run_dir / "metadata"
    run_dir.mkdir(parents=True, exist_ok=True)
    logs_dir.mkdir(parents=True, exist_ok=True)
    metadata_dir.mkdir(parents=True, exist_ok=True)

    status_path = run_dir / "run_status.json"
    if config.get("skip_if_successful", False) and status_path.is_file():
        try:
            previous = json.loads(status_path.read_text(encoding="utf-8"))
            if previous.get("status") == "ok":
                return RunResult(
                    run_id, phase, "skipped_successful", 0, str(run_dir), str(output_dir),
                    previous.get("prepared_script", ""), previous.get("source_script", ""),
                    count_output_files(output_dir), "Previously successful run skipped."
                )
        except Exception:
            pass

    if config.get("clean_output_before_run", False) and output_dir.exists():
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if language == "R":
        roots = [Path(p) for p in config["r_script_roots"]]
        project_cwd = Path(config["r_project_root"])
        executable = Path(config["rscript_bin"])
    elif language in {"PY", "PYTHON"}:
        roots = [Path(p) for p in config["python_script_roots"]]
        project_cwd = Path(config["python_project_root"])
        executable = Path(config["python_bin"])
    else:
        raise ValueError(f"Unsupported script_language: {language}")

    ensure_dir(project_cwd, f"{language} project root")
    ensure_file(executable, f"{language} executable")

    source_script, all_hits = find_script(source_name, roots)
    if source_script is None:
        raise FileNotFoundError(
            f"Source script not found: {source_name}\n"
            f"Search roots: {[str(p) for p in roots]}"
        )
    if len(all_hits) > 1:
        print(f"[WARN] Multiple scripts matched {source_name}; using {source_script}")
        for hit in all_hits:
            print(f"       candidate: {hit}")

    original_text = source_script.read_text(encoding="utf-8-sig", errors="strict")
    overrides_raw = row.get("overrides_json", "{}")
    if pd.isna(overrides_raw) or not str(overrides_raw).strip():
        overrides: Dict[str, Any] = {}
    else:
        overrides = json.loads(str(overrides_raw))

    patch_records: List[PatchRecord] = []
    patch_warnings: List[str] = []
    dependency_report: Dict[str, Any] = {}

    if language == "R":
        manifest_assignments = overrides.get("R_ASSIGN", {})
        input_assignments, dependency_report = resolve_r_inputs(phase, config)
        prepared_text, patch_records, patch_warnings = patch_r_script(
            original_text,
            manifest_assignments,
            input_assignments,
            output_dir,
            bool(config.get("force_isolated_output", True)),
        )
    else:
        manifest_assignments = overrides.get("PY_CONFIG", {})
        if "TEXT_REPLACE" in overrides and not config.get("allow_text_replace", False):
            raise RuntimeError(
                f"Run {run_id} requests TEXT_REPLACE, but CONFIG['allow_text_replace'] is False."
            )
        if manifest_assignments:
            prepared_text, patch_records, patch_warnings = patch_python_config(
                original_text,
                manifest_assignments,
                output_dir,
                bool(config.get("force_isolated_output", True)),
            )
        else:
            prepared_text = original_text
            if overrides:
                patch_warnings.append(f"Unsupported/non-patching override keys retained as metadata: {list(overrides)}")

    prepared_script = run_dir / source_script.name
    prepared_script.write_text(prepared_text, encoding="utf-8")

    patch_report = {
        "created_at": now_iso(),
        "run_id": run_id,
        "phase": phase,
        "source_script": str(source_script),
        "prepared_script": str(prepared_script),
        "working_directory": str(project_cwd),
        "output_directory": str(output_dir),
        "patches": [record.__dict__ for record in patch_records],
        "warnings": patch_warnings,
        "resolved_dependencies": dependency_report,
        "manifest_overrides": overrides,
    }
    json_dump(metadata_dir / "patch_and_dependency_report.json", patch_report)

    # Validate the prepared script before any execution.
    if language == "R":
        valid, validation_text = validate_r_script(
            prepared_script, executable, project_cwd, logs_dir / "syntax_validation.log"
        )
    else:
        valid, validation_text = validate_python_script(
            prepared_script, executable, project_cwd, logs_dir / "syntax_validation.log"
        )

    if not valid:
        result = RunResult(
            run_id, phase, "syntax_validation_failed", None, str(run_dir), str(output_dir),
            str(prepared_script), str(source_script), count_output_files(output_dir), validation_text[-2000:]
        )
        json_dump(status_path, {**result.__dict__, "finished_at": now_iso()})
        return result

    if not config.get("execute", False):
        result = RunResult(
            run_id, phase, "prepared_dry_run", None, str(run_dir), str(output_dir),
            str(prepared_script), str(source_script), count_output_files(output_dir),
            "Prepared and syntax-validated; execution disabled."
        )
        json_dump(status_path, {**result.__dict__, "finished_at": now_iso()})
        return result

    if language == "R":
        cmd = [str(executable), "--vanilla", str(prepared_script)]
    else:
        cmd = [str(executable), str(prepared_script)]

    env = prepare_environment(language, source_script, run_dir, output_dir, phase, run_id)
    print(f"执行命令: {cmd}")
    print(f"工作目录: {project_cwd}")
    print(f"输出目录: {output_dir}")

    started_at = now_iso()
    returncode = run_process_streaming(
        cmd,
        project_cwd,
        env,
        logs_dir / "stdout.log",
        logs_dir / "stderr.log",
    )
    n_outputs = count_output_files(output_dir)

    if returncode != 0:
        status = "execution_failed"
        message = f"Process returned {returncode}. See logs directory."
    elif config.get("require_nonempty_output", True) and n_outputs == 0:
        status = "no_outputs"
        message = "Process returned 0 but no files were created under the isolated output directory."
    else:
        status = "ok"
        message = f"Completed successfully with {n_outputs} output files."

    result = RunResult(
        run_id, phase, status, returncode, str(run_dir), str(output_dir),
        str(prepared_script), str(source_script), n_outputs, message
    )
    json_dump(
        status_path,
        {
            **result.__dict__,
            "started_at": started_at,
            "finished_at": now_iso(),
            "command": cmd,
            "working_directory": str(project_cwd),
        },
    )
    return result


