def timestamp_tag() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def json_dump(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(obj, ensure_ascii=False, indent=2, default=str),
        encoding="utf-8",
    )


def count_files(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for x in path.rglob("*") if x.is_file())


def choose_summary_dir(base: Path, policy: str) -> Path:
    if not base.exists() or count_files(base) == 0:
        base.mkdir(parents=True, exist_ok=True)
        return base
    policy = policy.lower().strip()
    if policy == "timestamp":
        target = base.parent / f"{base.name}_{timestamp_tag()}"
        target.mkdir(parents=True, exist_ok=False)
        return target
    raise FileExistsError(
        f"Summary directory already exists and is non-empty; nothing was overwritten:\n{base}"
    )


def resolve_run_dir(run_name: str, spec: Mapping[str, Any]) -> Path:
    if "run_dir_key" in spec:
        return Path(CONFIG[str(spec["run_dir_key"])])
    return Path(CONFIG["seed_robustness_root"]) / str(spec["relative_run_dir"])


def resolve_tables_dir(run_dir: Path) -> Path:
    candidates = [run_dir / "outputs" / "tables", run_dir / "tables"]
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    raise NotADirectoryError(f"Tables directory not found under: {run_dir}")


def flatten_json(obj: Any, prefix: str = "") -> Dict[str, Any]:
    out: Dict[str, Any] = {}
    if isinstance(obj, dict):
        for key, value in obj.items():
            name = f"{prefix}.{key}" if prefix else str(key)
            out.update(flatten_json(value, name))
    elif isinstance(obj, list):
        out[prefix] = json.dumps(obj, ensure_ascii=False)
    else:
        out[prefix] = obj
    return out


def read_json(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8-sig") as handle:
        return json.load(handle)


def infer_group_columns(frames: Sequence[pd.DataFrame]) -> List[str]:
    common = set(frames[0].columns)
    for frame in frames[1:]:
        common &= set(frame.columns)
    non_numeric: List[str] = []
    for column in frames[0].columns:
        if column not in common:
            continue
        if any(not pd.api.types.is_numeric_dtype(frame[column]) for frame in frames):
            non_numeric.append(column)
    return non_numeric


def combine_table(run_data: Mapping[str, Dict[str, Any]], table_key: str) -> pd.DataFrame:
    frames: List[pd.DataFrame] = []
    for run_name, data in run_data.items():
        frame = pd.read_csv(data[table_key], low_memory=False)
        frame.insert(0, "seed", int(data["seed"]))
        frame.insert(0, "run_name", run_name)
        frames.append(frame)
    return pd.concat(frames, ignore_index=True, sort=False)


def percentage_point_range(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").dropna()
    if values.empty:
        return float("nan")
    raw_range = float(values.max() - values.min())
    if float(values.abs().max()) <= 1.000001:
        return raw_range * 100.0
    return raw_range


def summarize_grouped_numeric(
    long_df: pd.DataFrame,
    group_cols: Sequence[str],
) -> pd.DataFrame:
    excluded = {"seed"}
    numeric_cols = [
        c for c in long_df.select_dtypes(include=[np.number]).columns
        if c not in excluded and c not in group_cols
    ]
    records: List[Dict[str, Any]] = []
    grouper: Any = list(group_cols) if len(group_cols) > 1 else group_cols[0]
    for keys, part in long_df.groupby(grouper, dropna=False):
        if not isinstance(keys, tuple):
            keys = (keys,)
        base = dict(zip(group_cols, keys))
        for metric in numeric_cols:
            values = pd.to_numeric(part[metric], errors="coerce").dropna()
            if values.empty:
                continue
            mean = float(values.mean())
            sd = float(values.std(ddof=1)) if len(values) > 1 else 0.0
            record = {
                **base,
                "metric": metric,
                "n_seeds": int(values.size),
                "mean": mean,
                "sd": sd,
                "min": float(values.min()),
                "max": float(values.max()),
                "range": float(values.max() - values.min()),
                "cv_abs": float(abs(sd / mean)) if mean != 0 else float("nan"),
                "range_percentage_points": percentage_point_range(values)
                    if ("pct" in metric.lower() or "percent" in metric.lower())
                    else float("nan"),
            }
            records.append(record)
    return pd.DataFrame(records)


def find_metric_column(columns: Iterable[str], include: Sequence[str], exclude: Sequence[str] = ()) -> Optional[str]:
    matches: List[str] = []
    for column in columns:
        low = column.lower()
        if all(token in low for token in include) and not any(token in low for token in exclude):
            matches.append(column)
    if not matches:
        return None
    return sorted(matches, key=lambda x: (len(x), x))[0]


def pairwise_state_consistency(run_data: Mapping[str, Dict[str, Any]]) -> pd.DataFrame:
    frames: Dict[str, pd.DataFrame] = {
        run_name: pd.read_csv(data["velocity"], low_memory=False)
        for run_name, data in run_data.items()
    }
    id_candidates = ["cell_state_id", "state_id"]
    id_col = next((c for c in id_candidates if all(c in df.columns for df in frames.values())), None)
    if id_col is None:
        raise KeyError("No common state identifier column found in velocity tables.")

    common_columns = set.intersection(*(set(df.columns) for df in frames.values()))
    numeric_columns = [
        c for c in common_columns
        if all(pd.api.types.is_numeric_dtype(df[c]) for df in frames.values())
    ]
    preferred = [
        c for c in numeric_columns
        if any(token in c.lower() for token in ["projection", "cosine", "similarity", "velocity_norm"])
    ]
    metrics = sorted(preferred or numeric_columns)

    run_names = list(frames)
    records: List[Dict[str, Any]] = []
    for i in range(len(run_names)):
        for j in range(i + 1, len(run_names)):
            left_name, right_name = run_names[i], run_names[j]
            merged = frames[left_name][[id_col] + metrics].merge(
                frames[right_name][[id_col] + metrics],
                on=id_col,
                how="inner",
                suffixes=("_left", "_right"),
            )
            for metric in metrics:
                x = pd.to_numeric(merged[f"{metric}_left"], errors="coerce")
                y = pd.to_numeric(merged[f"{metric}_right"], errors="coerce")
                valid = x.notna() & y.notna() & np.isfinite(x) & np.isfinite(y)
                xv = x[valid]
                yv = y[valid]
                if len(xv) < 3:
                    continue
                pearson = float(xv.corr(yv, method="pearson"))
                spearman = float(xv.rank(method="average").corr(yv.rank(method="average")))
                sign_agreement = float((np.sign(xv.to_numpy()) == np.sign(yv.to_numpy())).mean())
                records.append({
                    "run_left": left_name,
                    "run_right": right_name,
                    "metric": metric,
                    "n_common_states": int(len(xv)),
                    "pearson": pearson,
                    "spearman": spearman,
                    "sign_agreement": sign_agreement,
                    "mean_absolute_difference": float(np.mean(np.abs(xv.to_numpy() - yv.to_numpy()))),
                })
    return pd.DataFrame(records)


def metric_value(metrics_wide: pd.DataFrame, candidates: Sequence[str]) -> Optional[pd.Series]:
    for candidate in candidates:
        if candidate in metrics_wide.columns:
            return pd.to_numeric(metrics_wide[candidate], errors="coerce")
    for column in metrics_wide.columns:
        low = column.lower()
        if any(candidate.lower() in low for candidate in candidates):
            return pd.to_numeric(metrics_wide[column], errors="coerce")
    return None


def main() -> None:
    summary_dir = choose_summary_dir(
        Path(CONFIG["summary_output_dir"]),
        str(CONFIG["existing_output_policy"]),
    )

    run_data: Dict[str, Dict[str, Any]] = {}
    integrity_records: List[Dict[str, Any]] = []

    for run_name, spec in RUNS.items():
        run_dir = resolve_run_dir(run_name, spec)
        tables_dir = resolve_tables_dir(run_dir)
        data: Dict[str, Any] = {
            "seed": int(spec["seed"]),
            "run_dir": run_dir,
            "tables_dir": tables_dir,
        }
        missing: List[str] = []
        for key, filename in TABLES.items():
            path = tables_dir / filename
            data[key] = path
            if not path.is_file() or path.stat().st_size == 0:
                missing.append(filename)

        status_path = run_dir / "run_status.json"
        run_status = "not_found"
        returncode: Any = None
        if status_path.is_file():
            status_obj = read_json(status_path)
            run_status = status_obj.get("status", "unknown")
            returncode = status_obj.get("returncode")

        integrity_records.append({
            "run_name": run_name,
            "seed": int(spec["seed"]),
            "run_dir": str(run_dir),
            "tables_dir": str(tables_dir),
            "run_status": run_status,
            "returncode": returncode,
            "missing_required_tables": "; ".join(missing),
            "integrity_ok": len(missing) == 0 and run_status in {"ok", "not_found"},
        })
        if missing:
            raise FileNotFoundError(f"{run_name} is missing: {missing}")
        run_data[run_name] = data

    integrity_df = pd.DataFrame(integrity_records)
    integrity_df.to_csv(summary_dir / "01_run_integrity_check.csv", index=False, encoding="utf-8-sig")

    # Final metrics, one row per seed.
    metrics_records: List[Dict[str, Any]] = []
    for run_name, data in run_data.items():
        flat = flatten_json(read_json(data["metrics"]))
        metrics_records.append({"run_name": run_name, "seed": data["seed"], **flat})
    metrics_df = pd.DataFrame(metrics_records).sort_values("seed")
    metrics_df.to_csv(summary_dir / "02_final_metrics_across_seeds.csv", index=False, encoding="utf-8-sig")

    numeric_metric_cols = [
        c for c in metrics_df.select_dtypes(include=[np.number]).columns if c != "seed"
    ]
    metric_summary_records: List[Dict[str, Any]] = []
    for metric in numeric_metric_cols:
        values = pd.to_numeric(metrics_df[metric], errors="coerce").dropna()
        if values.empty:
            continue
        metric_summary_records.append({
            "metric": metric,
            "n_seeds": int(len(values)),
            "mean": float(values.mean()),
            "sd": float(values.std(ddof=1)) if len(values) > 1 else 0.0,
            "min": float(values.min()),
            "max": float(values.max()),
            "range": float(values.max() - values.min()),
            "relative_range_to_mean": float((values.max() - values.min()) / abs(values.mean()))
                if values.mean() != 0 else float("nan"),
        })
    pd.DataFrame(metric_summary_records).to_csv(
        summary_dir / "03_final_metrics_stability_summary.csv",
        index=False,
        encoding="utf-8-sig",
    )

    table_specs = [
        ("stage", "04_stage_directionality_across_seeds.csv", "05_stage_stability_summary.csv"),
        ("disease", "06_disease_directionality_across_seeds.csv", "07_disease_stability_summary.csv"),
        ("celltype", "08_celltype_directionality_across_seeds.csv", "09_celltype_stability_summary.csv"),
        ("cluster", "10_cluster_directionality_across_seeds.csv", "11_cluster_stability_summary.csv"),
    ]
    summaries: Dict[str, pd.DataFrame] = {}
    combined: Dict[str, pd.DataFrame] = {}
    for key, long_name, summary_name in table_specs:
        long_df = combine_table(run_data, key)
        raw_frames = [pd.read_csv(run_data[r][key], low_memory=False) for r in run_data]
        common_columns = set.intersection(*(set(frame.columns) for frame in raw_frames))
        group_cols: List[str] = []
        for candidate in GROUP_COLUMN_CANDIDATES.get(key, []):
            if all(column in common_columns for column in candidate):
                group_cols = candidate
                break
        if not group_cols:
            group_cols = infer_group_columns(raw_frames)
        if not group_cols:
            raise RuntimeError(f"Could not infer group columns for {key} table.")
        summary_df = summarize_grouped_numeric(long_df, group_cols)
        long_df.to_csv(summary_dir / long_name, index=False, encoding="utf-8-sig")
        summary_df.to_csv(summary_dir / summary_name, index=False, encoding="utf-8-sig")
        combined[key] = long_df
        summaries[key] = summary_df

    thresholds = CONFIG["thresholds"]
    celltype_flags = summaries["celltype"].copy()
    celltype_flags = celltype_flags[
        celltype_flags["range_percentage_points"].notna()
        & (celltype_flags["range_percentage_points"] >= float(thresholds["celltype_flag_percentage_point_range"]))
    ].sort_values("range_percentage_points", ascending=False)
    celltype_flags.to_csv(
        summary_dir / "12_celltype_seed_sensitivity_flags.csv",
        index=False,
        encoding="utf-8-sig",
    )

    cluster_flags = summaries["cluster"].copy()
    cluster_flags = cluster_flags[
        cluster_flags["range_percentage_points"].notna()
        & (cluster_flags["range_percentage_points"] >= float(thresholds["cluster_flag_percentage_point_range"]))
    ].sort_values("range_percentage_points", ascending=False)
    cluster_flags.to_csv(
        summary_dir / "13_cluster_seed_sensitivity_flags.csv",
        index=False,
        encoding="utf-8-sig",
    )

    state_consistency = pairwise_state_consistency(run_data)
    state_consistency.to_csv(
        summary_dir / "14_state_level_pairwise_consistency.csv",
        index=False,
        encoding="utf-8-sig",
    )

    # Operational assessment.
    val_r2 = metric_value(metrics_df, ["val_r2", "validation_r2"])
    val_mse = metric_value(metrics_df, ["val_mse", "validation_mse"])
    val_r2_range = float(val_r2.max() - val_r2.min()) if val_r2 is not None else float("nan")
    val_mse_relative_range = (
        float((val_mse.max() - val_mse.min()) / abs(val_mse.mean()))
        if val_mse is not None and val_mse.mean() != 0 else float("nan")
    )

    stage_pct = summaries["stage"]["range_percentage_points"].dropna()
    disease_pct = summaries["disease"]["range_percentage_points"].dropna()
    max_stage_pp = float(stage_pct.max()) if not stage_pct.empty else float("nan")
    max_disease_pp = float(disease_pct.max()) if not disease_pct.empty else float("nan")

    projection_rows = state_consistency[
        state_consistency["metric"].str.contains("projection|cosine|similarity", case=False, regex=True)
    ]
    median_spearman = float(projection_rows["spearman"].median()) if not projection_rows.empty else float("nan")
    median_sign = float(projection_rows["sign_agreement"].median()) if not projection_rows.empty else float("nan")

    checks = {
        "all_runs_complete": bool(integrity_df["integrity_ok"].all()),
        "val_r2_stable": bool(val_r2_range <= float(thresholds["max_val_r2_range"]))
            if math.isfinite(val_r2_range) else False,
        "val_mse_stable": bool(val_mse_relative_range <= float(thresholds["max_relative_val_mse_range"]))
            if math.isfinite(val_mse_relative_range) else False,
        "stage_directionality_stable": bool(max_stage_pp <= float(thresholds["max_stage_percentage_point_range"]))
            if math.isfinite(max_stage_pp) else False,
        "disease_directionality_stable": bool(max_disease_pp <= float(thresholds["max_disease_percentage_point_range"]))
            if math.isfinite(max_disease_pp) else False,
        "state_projection_rank_stable": bool(median_spearman >= float(thresholds["min_state_projection_spearman"]))
            if math.isfinite(median_spearman) else False,
        "state_projection_sign_stable": bool(median_sign >= float(thresholds["min_state_projection_sign_agreement"]))
            if math.isfinite(median_sign) else False,
    }

    n_failed = sum(not value for value in checks.values())
    if n_failed == 0:
        verdict = "PASS_GLOBAL_SEED_STABILITY"
    elif checks["all_runs_complete"] and checks["val_r2_stable"] and checks["val_mse_stable"]:
        verdict = "CAUTION_DIRECTIONALITY_SEED_SENSITIVITY"
    else:
        verdict = "FAIL_OR_REVIEW_REQUIRED"

    assessment = {
        "verdict": verdict,
        "operational_thresholds": thresholds,
        "observed": {
            "val_r2_range": val_r2_range,
            "val_mse_relative_range": val_mse_relative_range,
            "max_stage_percentage_point_range": max_stage_pp,
            "max_disease_percentage_point_range": max_disease_pp,
            "median_state_projection_spearman": median_spearman,
            "median_state_projection_sign_agreement": median_sign,
            "n_celltype_sensitivity_flags": int(len(celltype_flags)),
            "n_cluster_sensitivity_flags": int(len(cluster_flags)),
        },
        "checks": checks,
        "interpretation_note": (
            "A global pass does not imply that every cell type or cluster is stable. "
            "Review the sensitivity-flag tables before biological interpretation."
        ),
    }
    json_dump(summary_dir / "15_overall_seed_stability_assessment.json", assessment)

    print("\nSeed robustness summary completed.")
    print("Output:", summary_dir)
    print("Verdict:", verdict)
    print(json.dumps(assessment["observed"], ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
