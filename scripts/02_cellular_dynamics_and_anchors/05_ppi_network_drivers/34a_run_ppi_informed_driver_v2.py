def make_candidate_id(df: pd.DataFrame) -> pd.Series:
    columns = [col for col in CONFIG["candidate_context_columns"] if col in df.columns]
    values = df[columns].copy()
    for col in columns:
        values[col] = values[col].map(lambda value: "NA" if pd.isna(value) else normalize_key(value))
    return values.astype(str).agg("|".join, axis=1)


def build_local_gene_table(evidence: pd.DataFrame) -> pd.DataFrame:
    grouped = evidence.groupby("gene_symbol", as_index=False).agg(
        local_gene_score_mean=("local_evidence_score", "mean"),
        local_gene_score_max=("local_evidence_score", "max"),
        mean_context_ode_weight=("context_ode_reliability_weight", "mean"),
        min_context_ode_weight=("context_ode_reliability_weight", "min"),
        ode_warning_rate=("context_has_ode_warning", "mean"),
        n_contexts=("gene_symbol", "size"),
        n_celltypes=("celltype_marker_based", "nunique") if "celltype_marker_based" in evidence.columns else ("gene_symbol", "size"),
        n_clusters=("cluster_default", "nunique") if "cluster_default" in evidence.columns else ("gene_symbol", "size"),
        active_support_mean=("is_active_progression_state_fraction", "mean"),
        terminal_support_mean=("is_terminal_convergent_state_fraction", "mean"),
    )
    max_weight = float(CONFIG["gene_seed_max_weight"])
    mean_weight = float(CONFIG["gene_seed_mean_weight"])
    denominator = max_weight + mean_weight
    grouped["gene_seed_evidence_score"] = (
        max_weight * grouped["local_gene_score_max"]
        + mean_weight * grouped["local_gene_score_mean"]
    ) / denominator
    return grouped


def run_scenario(
    scenario: Mapping[str, Any],
    evidence: pd.DataFrame,
    local_gene: pd.DataFrame,
    ppi_models: Mapping[str, Dict[str, Any]],
) -> Tuple[pd.DataFrame, pd.DataFrame, Dict[str, Any]]:
    ppi_name = str(scenario["ppi_name"])
    model = ppi_models[ppi_name]
    genes = model["genes"]
    gene_to_index = model["gene_to_index"]
    ode_power = float(scenario.get("ode_weight_power", 1.0))

    seed = np.zeros(len(genes), dtype=float)
    for row in local_gene.itertuples(index=False):
        idx = gene_to_index.get(str(row.gene_symbol))
        if idx is None:
            continue
        seed[idx] = float(row.gene_seed_evidence_score) * (
            float(row.mean_context_ode_weight) ** ode_power
        )
    raw_propagation, iterations, final_delta = rwr_sparse(
        model["transition"],
        seed,
        restart_prob=float(scenario.get("restart_prob", 0.70)),
        max_iter=int(scenario.get("max_iter", 120)),
        tol=float(scenario.get("tol", 1e-11)),
    )
    propagation_percentile = pd.Series(raw_propagation).rank(method="average", pct=True).to_numpy(dtype=float)
    propagation_weight = float(CONFIG["ppi_propagation_weight"])
    degree_weight = float(CONFIG["ppi_degree_weight"])
    ppi_component = (
        propagation_weight * propagation_percentile
        + degree_weight * model["degree_score"]
    ) / (propagation_weight + degree_weight)
    ppi_frame = pd.DataFrame({
        "gene_symbol": genes,
        "ppi_propagation_raw": raw_propagation,
        "ppi_propagation_score": propagation_percentile,
        "ppi_degree": model["degree"],
        "ppi_weighted_degree": model["weighted_degree"],
        "ppi_degree_score": model["degree_score"],
        "ppi_component_score": ppi_component,
    })

    gene_out = local_gene.merge(ppi_frame, on="gene_symbol", how="left")
    for col in [
        "ppi_propagation_raw", "ppi_propagation_score", "ppi_degree",
        "ppi_weighted_degree", "ppi_degree_score", "ppi_component_score",
    ]:
        gene_out[col] = pd.to_numeric(gene_out[col], errors="coerce").fillna(0.0)
    gene_out["in_ppi_network"] = gene_out["ppi_degree"] > 0

    local_weight = float(scenario.get("local_weight", 0.55))
    ppi_weight = float(scenario.get("ppi_weight", 0.45))
    denominator = local_weight + ppi_weight
    gene_out["gene_driver_score_raw"] = (
        local_weight * gene_out["gene_seed_evidence_score"]
        + ppi_weight * gene_out["ppi_component_score"]
    ) / denominator
    gene_out["gene_driver_score"] = gene_out["gene_driver_score_raw"] * (
        gene_out["mean_context_ode_weight"] ** ode_power
    )
    gene_out["scenario"] = str(scenario["name"])
    gene_out["ppi_name"] = ppi_name
    gene_out["is_primary_scenario"] = gene_out["scenario"] == CONFIG["primary_scenario"]
    gene_out = gene_out.sort_values("gene_driver_score", ascending=False).reset_index(drop=True)
    gene_out["rank_in_scenario"] = np.arange(1, len(gene_out) + 1)
    gene_out["score_percentile_in_scenario"] = gene_out["gene_driver_score"].rank(method="average", pct=True)
    gene_out["in_top_10pct"] = gene_out["score_percentile_in_scenario"] >= 0.90
    gene_out["in_top_20pct"] = gene_out["score_percentile_in_scenario"] >= 0.80
    for topk in CONFIG["topk_values"]:
        gene_out[f"in_top_{topk}"] = gene_out["rank_in_scenario"] <= int(topk)

    context_out = evidence.merge(
        gene_out[[
            "gene_symbol", "ppi_propagation_raw", "ppi_propagation_score",
            "ppi_degree", "ppi_weighted_degree", "ppi_degree_score",
            "ppi_component_score", "in_ppi_network",
        ]],
        on="gene_symbol",
        how="left",
    )
    context_out["driver_score_raw"] = (
        local_weight * context_out["local_evidence_score"]
        + ppi_weight * context_out["ppi_component_score"].fillna(0.0)
    ) / denominator
    context_out["driver_score"] = context_out["driver_score_raw"] * (
        context_out["context_ode_reliability_weight"] ** ode_power
    )
    context_out["scenario"] = str(scenario["name"])
    context_out["ppi_name"] = ppi_name
    context_out["is_primary_scenario"] = context_out["scenario"] == CONFIG["primary_scenario"]
    context_out["candidate_id"] = make_candidate_id(context_out)
    context_out = context_out.sort_values("driver_score", ascending=False).reset_index(drop=True)
    context_out["rank_in_scenario"] = np.arange(1, len(context_out) + 1)
    context_out["score_percentile_in_scenario"] = context_out["driver_score"].rank(method="average", pct=True)
    context_out["in_top_10pct"] = context_out["score_percentile_in_scenario"] >= 0.90
    context_out["in_top_20pct"] = context_out["score_percentile_in_scenario"] >= 0.80
    for topk in CONFIG["topk_values"]:
        context_out[f"in_top_{topk}"] = context_out["rank_in_scenario"] <= int(topk)

    run_qc = {
        "scenario": str(scenario["name"]),
        "ppi_name": ppi_name,
        "restart_prob": float(scenario.get("restart_prob", 0.70)),
        "iterations": int(iterations),
        "final_l1_delta": final_delta,
        "n_network_genes": int(len(genes)),
        "n_evidence_genes": int(len(local_gene)),
        "n_evidence_genes_in_ppi": int(gene_out["in_ppi_network"].sum()),
    }
    return context_out, gene_out, run_qc


