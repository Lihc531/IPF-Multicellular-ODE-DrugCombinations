def load_velocity_support() -> Tuple[Optional[pd.DataFrame], Dict[str, Any]]:
    spec = CONFIG.get("ode_velocity_table", {})
    if not bool(spec.get("enabled", False)):
        return None, {"enabled": False, "status": "disabled"}
    path = Path(str(spec.get("path", "")))
    if not path.is_file():
        if bool(spec.get("required", False)):
            raise FileNotFoundError(f"Required ODE velocity table not found: {path}")
        return None, {"enabled": True, "status": "not_found_optional", "path": str(path)}

    raw = read_table(path).rename(columns=lambda col: clean_colname(col))
    state_col = find_column(
        raw.columns,
        [str(spec.get("cell_state_id_col", "cell_state_id")), "cell_state_id", "state_id"],
        required=True,
        label="velocity cell_state_id",
    )
    stage_col = find_column(raw.columns, ["axis_v2_stage", "stage"], required=False)
    axis_state_col = find_column(raw.columns, ["mean_axis_v2_score", "axis_v2_score"], required=False)
    axis_proj_col = find_column(raw.columns, ["velocity_axis_projection", "axis_projection"], required=False)
    fibrosis_proj_col = find_column(raw.columns, ["velocity_fibrosis_projection", "fibrosis_projection"], required=False)
    terminal_col = find_column(raw.columns, ["delta_terminal_similarity", "terminal_similarity"], required=False)

    out = pd.DataFrame({"cell_state_id": raw[state_col].astype(str)})
    column_map = {
        "axis_v2_stage_velocity": stage_col,
        "mean_axis_v2_score_velocity": axis_state_col,
        "velocity_axis_projection": axis_proj_col,
        "velocity_fibrosis_projection": fibrosis_proj_col,
        "delta_terminal_similarity": terminal_col,
    }
    for target, source in column_map.items():
        if source is None:
            continue
        if target == "axis_v2_stage_velocity":
            out[target] = raw[source]
        else:
            out[target] = pd.to_numeric(raw[source], errors="coerce")

    active_stages = set(map(str, spec.get("active_progression_stages", [])))
    terminal_stages = set(map(str, spec.get("terminal_stages", [])))
    stage_values = out.get("axis_v2_stage_velocity", pd.Series("", index=out.index)).astype(str)
    axis_projection = out.get("velocity_axis_projection", pd.Series(np.nan, index=out.index))
    fibrosis_projection = out.get("velocity_fibrosis_projection", pd.Series(np.nan, index=out.index))
    axis_state = out.get("mean_axis_v2_score_velocity", pd.Series(np.nan, index=out.index))
    terminal_similarity = out.get("delta_terminal_similarity", pd.Series(np.nan, index=out.index))

    active = stage_values.isin(active_stages)
    if axis_projection.notna().any():
        active &= axis_projection.fillna(0) > 0
    if fibrosis_projection.notna().any():
        active &= fibrosis_projection.fillna(0) > 0

    terminal_like = stage_values.isin(terminal_stages)
    if axis_state.notna().any():
        axis_threshold = float(axis_state.quantile(float(spec.get("high_axis_quantile", 0.75))))
        terminal_like |= axis_state >= axis_threshold
    else:
        axis_threshold = float("nan")

    if terminal_similarity.notna().any():
        terminal_threshold = float(
            terminal_similarity.quantile(float(spec.get("high_terminal_similarity_quantile", 0.75)))
        )
        terminal_convergent = terminal_like & (terminal_similarity >= terminal_threshold)
    else:
        terminal_threshold = float("nan")
        terminal_convergent = terminal_like

    support_parts: List[pd.Series] = []
    for series in [axis_projection, fibrosis_projection, terminal_similarity]:
        if series.notna().any():
            support_parts.append(normalize_score(series, "positive", "rank_percentile"))
    if support_parts:
        support = pd.concat(support_parts, axis=1).mean(axis=1)
    else:
        support = pd.Series(0.5, index=out.index)

    out["is_active_progression_state"] = active.astype(bool)
    out["is_terminal_like_state"] = terminal_like.astype(bool)
    out["is_terminal_convergent_state"] = terminal_convergent.astype(bool)
    out["state_ode_direction_support_score"] = support.astype(float)
    out = out.drop_duplicates("cell_state_id")

    qc = {
        "enabled": True,
        "status": "loaded",
        "path": str(path),
        "n_rows": int(len(out)),
        "n_active_progression_states": int(out["is_active_progression_state"].sum()),
        "n_terminal_like_states": int(out["is_terminal_like_state"].sum()),
        "n_terminal_convergent_states": int(out["is_terminal_convergent_state"].sum()),
        "high_axis_threshold": axis_threshold,
        "high_terminal_similarity_threshold": terminal_threshold,
    }
    return out, qc


