def validate_pycharm_configuration() -> Dict[str, Any]:
    """Fail early with one consolidated report for missing or inconsistent inputs."""
    problems: List[str] = []
    warnings: List[str] = []
    resolved: Dict[str, Any] = {}

    if sys.version_info < (3, 9):
        problems.append(
            f"Python 3.9+ is required; PyCharm currently uses {sys.version.split()[0]}"
        )
    if sp is None:
        problems.append(
            "SciPy cannot be imported by the selected PyCharm interpreter: "
            f"{SCIPY_IMPORT_ERROR}"
        )

    scenario_names = [str(item["name"]) for item in CONFIG.get("scenarios", [])]
    if CONFIG.get("primary_scenario") not in scenario_names:
        problems.append(
            f"primary_scenario={CONFIG.get('primary_scenario')!r} is absent from CONFIG['scenarios']"
        )
    ppi_names = {str(item["name"]) for item in CONFIG.get("ppi_edge_tables", [])}
    for scenario in CONFIG.get("scenarios", []):
        if str(scenario.get("ppi_name")) not in ppi_names:
            problems.append(
                f"Scenario {scenario.get('name')!r} refers to unknown PPI network "
                f"{scenario.get('ppi_name')!r}"
            )

    required_specs: List[Tuple[str, Any, bool]] = [
        ("ODE robustness weights", CONFIG.get("ode_robustness_weights_path"), True),
    ]
    for index, spec in enumerate(CONFIG.get("gene_evidence_tables", []), start=1):
        required_specs.append((f"Gene evidence table {index}", spec.get("path"), False))
    for spec in CONFIG.get("ppi_edge_tables", []):
        required_specs.append((f"PPI table {spec.get('name')}", spec.get("path"), False))

    for label, path_like, allow_zip in required_specs:
        try:
            resolved_path = resolve_existing_path(path_like, allow_zip_fallback=allow_zip)
            resolved[label] = str(resolved_path)
        except Exception:
            suffix_note = " (or the same path plus .zip)" if allow_zip else ""
            problems.append(f"{label}: not found: {path_like}{suffix_note}")

    velocity_spec = CONFIG.get("ode_velocity_table", {})
    if bool(velocity_spec.get("enabled", False)):
        velocity_path = Path(str(velocity_spec.get("path", "")))
        if velocity_path.is_file():
            resolved["Optional ODE velocity table"] = str(velocity_path)
        elif bool(velocity_spec.get("required", False)):
            problems.append(f"Required ODE velocity table: not found: {velocity_path}")
        else:
            warnings.append(
                "Optional ODE velocity table is absent; the workflow will use the "
                "direction score already present in the gene-evidence table."
            )

    output_root = Path(str(CONFIG.get("output_root", "")))
    if not str(output_root).strip():
        problems.append("output_root is empty")
    else:
        try:
            output_root.parent.mkdir(parents=True, exist_ok=True)
            probe = output_root.parent / ".34a_pycharm_write_test.tmp"
            probe.write_text("ok", encoding="utf-8")
            probe.unlink(missing_ok=True)
            resolved["Output root"] = str(output_root)
        except Exception as exc:
            problems.append(f"Output root is not writable: {output_root} ({exc})")

    if warnings:
        print("[PRECHECK WARNINGS]", flush=True)
        for item in warnings:
            print(f"  - {item}", flush=True)

    if problems:
        message = [
            "PyCharm pre-run validation failed.",
            f"Edit {PATH_CONFIG_FILE.name} beside the script, then run again:",
        ]
        message.extend(f"  - {item}" for item in problems)
        raise RuntimeError("\n".join(message))

    print("[PRECHECK OK] Required inputs and output location are available.", flush=True)
    for label, value in resolved.items():
        print(f"  {label}: {value}", flush=True)
    return {"resolved_paths": resolved, "warnings": warnings}


