def add_normalized_join_keys(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    mapping = {
        "celltype_marker_based": "_celltype_key",
        "cluster_default": "_cluster_key",
        "axis_v2_stage": "_stage_key",
        "Disease_Identity": "_disease_key",
    }
    for source, target in mapping.items():
        if source in out.columns:
            out[target] = out[source].map(normalize_key)
    return out


def join_ode_weights(evidence: pd.DataFrame, weights: Mapping[str, Any]) -> pd.DataFrame:
    out = add_normalized_join_keys(evidence)
    plans = [
        ("cluster", ["_celltype_key", "_cluster_key"], ["celltype_marker_based", "cluster_default"]),
        ("celltype", ["_celltype_key"], ["celltype_marker_based"]),
        ("stage", ["_stage_key"], ["axis_v2_stage"]),
        ("disease", ["_disease_key"], ["Disease_Identity"]),
    ]
    for level, key_cols, original_cols in plans:
        table = add_normalized_join_keys(weights[level])
        if not all(col in out.columns for col in key_cols):
            continue
        if not all(col in table.columns for col in key_cols):
            continue
        keep = key_cols + [
            col for col in table.columns
            if col not in key_cols + original_cols
            and (
                col.startswith("ode_")
                or col in {"seed_unstable", "threshold_unstable", "small_group"}
            )
        ]
        table = table[keep].drop_duplicates(key_cols)
        table = table.rename(columns={
            col: f"{level}_{col}" for col in table.columns if col not in key_cols
        })
        out = out.merge(table, on=key_cols, how="left")

    weight_cols = [
        col for col in out.columns
        if col.endswith("ode_reliability_weight")
        and col.startswith(("cluster_", "celltype_", "stage_", "disease_"))
    ]
    if weight_cols:
        values = out[weight_cols].apply(pd.to_numeric, errors="coerce")
        positive = values.where(values > 0)
        counts = positive.notna().sum(axis=1)
        log_sum = np.log(positive).sum(axis=1, skipna=True)
        geometric = np.exp(log_sum / counts.replace(0, np.nan))
        out["context_ode_reliability_weight"] = geometric.fillna(1.0).clip(0, 1)
        out["n_ode_weight_levels_joined"] = counts.astype(int)
    else:
        out["context_ode_reliability_weight"] = 1.0
        out["n_ode_weight_levels_joined"] = 0

    flag_cols = [
        col for col in out.columns
        if col.endswith(("seed_unstable", "threshold_unstable", "small_group"))
    ]
    for col in flag_cols:
        out[col] = out[col].fillna(False).astype(bool)
    out["context_has_ode_warning"] = out[flag_cols].any(axis=1) if flag_cols else False
    return out


