def add_gene_categories(
    gene_tiers: pd.DataFrame,
    context_scores: pd.DataFrame,
) -> pd.DataFrame:
    out = gene_tiers.copy()
    primary_context = context_scores[context_scores["scenario"] == CONFIG["primary_scenario"]].copy()
    category_config = CONFIG["category_thresholds"]

    context_agg = primary_context.groupby("gene_symbol", as_index=False).agg(
        active_progression_support=("is_active_progression_state_fraction", "mean"),
        terminal_maintenance_support=("is_terminal_convergent_state_fraction", "mean"),
        n_primary_contexts=("candidate_id", "nunique"),
        n_primary_celltypes=("celltype_marker_based", "nunique") if "celltype_marker_based" in primary_context.columns else ("candidate_id", "size"),
        primary_ppi_component=("ppi_component_score", "mean"),
    )

    if "celltype_marker_based" in primary_context.columns:
        by_celltype = primary_context.groupby(["gene_symbol", "celltype_marker_based"], as_index=False)["driver_score"].sum()
        totals = by_celltype.groupby("gene_symbol")["driver_score"].sum().replace(0, np.nan)
        maxima = by_celltype.groupby("gene_symbol")["driver_score"].max()
        specificity = (maxima / totals).fillna(0.0).rename("max_celltype_driver_share").reset_index()
        context_agg = context_agg.merge(specificity, on="gene_symbol", how="left")
    else:
        context_agg["max_celltype_driver_share"] = 1.0

    out = out.merge(context_agg, on="gene_symbol", how="left")
    supported_tier = out["ppi_driver_tier"].isin([
        "TIER_A_HIGH_CONFIDENCE",
        "TIER_B_ROBUST_BUT_CAUTION",
    ])
    ppi_threshold = float(out["primary_ppi_component"].quantile(
        float(category_config["shared_hub_ppi_quantile"])
    ))
    out["active_progression_driver"] = (
        supported_tier
        & (out["active_progression_support"] >= float(category_config["min_active_support"]))
    )
    out["terminal_state_maintenance_driver"] = (
        supported_tier
        & (out["terminal_maintenance_support"] >= float(category_config["min_terminal_support"]))
    )
    out["celltype_specific_driver"] = (
        supported_tier
        & (out["max_celltype_driver_share"] >= float(category_config["celltype_specific_share"]))
    )
    out["shared_profibrotic_hub"] = (
        supported_tier
        & (out["n_primary_celltypes"] >= int(category_config["shared_hub_min_celltypes"]))
        & (out["primary_ppi_component"] >= ppi_threshold)
    )
    out["n_driver_categories"] = out[[
        "active_progression_driver", "terminal_state_maintenance_driver",
        "celltype_specific_driver", "shared_profibrotic_hub",
    ]].sum(axis=1)
    return out


