def infer_context_column(df: pd.DataFrame, requested: Any, kind: str) -> Optional[str]:
    if requested is None:
        return None
    if requested != "auto":
        if requested not in df.columns:
            raise KeyError(f"Configured {kind} column not found: {requested}")
