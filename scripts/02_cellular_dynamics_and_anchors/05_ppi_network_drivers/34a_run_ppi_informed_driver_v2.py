def now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def timestamp_tag() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def json_dump(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2, default=str), encoding="utf-8")


def count_files(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for item in path.rglob("*") if item.is_file())


def choose_output_dir(base: Path, policy: str) -> Path:
    if not base.exists() or count_files(base) == 0:
        base.mkdir(parents=True, exist_ok=True)
        return base
    policy = policy.strip().lower()
    if policy == "timestamp":
        target = base.parent / f"{base.name}_{timestamp_tag()}"
        target.mkdir(parents=True, exist_ok=False)
        return target
    if policy == "overwrite":
        base.mkdir(parents=True, exist_ok=True)
        return base
    raise FileExistsError(
        f"Output directory is non-empty and was preserved: {base}\n"
        "Use existing_output_policy='timestamp' or inspect before using 'overwrite'."
    )


def resolve_existing_path(path_like: Any, allow_zip_fallback: bool = False) -> Path:
    path = Path(str(path_like))
    if path.exists():
        return path
    if allow_zip_fallback and path.suffix.lower() != ".zip":
        zipped = Path(str(path) + ".zip")
        if zipped.exists():
            return zipped
    raise FileNotFoundError(f"Input not found: {path}")


def file_sha256(path: Path, block_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            block = handle.read(block_size)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def clean_colname(name: Any) -> str:
    return str(name).strip().replace(" ", "_")


def canonical_col_token(value: Any) -> str:
    return re.sub(r"[^a-z0-9]+", "", str(value).strip().lower())


def normalize_gene(value: Any) -> str:
    if pd.isna(value):
        return ""
    return str(value).strip().upper()


def normalize_key(value: Any) -> str:
    if pd.isna(value):
        return ""
    text = str(value).strip()
    try:
        numeric = float(text)
        if math.isfinite(numeric) and numeric.is_integer():
            text = str(int(numeric))
    except (TypeError, ValueError):
        pass
    return re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_").upper()


def detect_delimiter(path: Path) -> str:
    with path.open("r", encoding="utf-8-sig", errors="replace") as handle:
        first_line = handle.readline()
    candidates = ["\t", ",", ";", "|"]
    counts = {sep: first_line.count(sep) for sep in candidates}
    best = max(counts, key=counts.get)
    if counts[best] == 0:
        return ","
    return best


def read_table(path_like: Any) -> pd.DataFrame:
    path = resolve_existing_path(path_like)
    suffix = path.suffix.lower()
    if suffix in {".xlsx", ".xls"}:
        return pd.read_excel(path)
    if suffix in {".csv", ".tsv", ".tab", ".txt"}:
        sep = detect_delimiter(path)
        return pd.read_csv(path, sep=sep, low_memory=False)
    raise ValueError(f"Unsupported table format: {path}")


def read_csv_from_dir_or_zip(source: Path, filename: str) -> pd.DataFrame:
    if source.is_dir():
        target = source / filename
        if not target.is_file():
            raise FileNotFoundError(f"Missing {filename} in {source}")
        return pd.read_csv(target, low_memory=False)
    if source.is_file() and source.suffix.lower() == ".zip":
        with zipfile.ZipFile(source) as archive:
            hits = [name for name in archive.namelist() if name.endswith(filename)]
            if not hits:
                raise FileNotFoundError(f"Missing {filename} in {source}")
            with archive.open(hits[0]) as handle:
                return pd.read_csv(handle, low_memory=False)
    raise FileNotFoundError(f"Expected ODE weight directory or zip: {source}")


def read_json_from_dir_or_zip(source: Path, filename: str) -> Dict[str, Any]:
    if source.is_dir():
        target = source / filename
        if not target.is_file():
            return {}
        return json.loads(target.read_text(encoding="utf-8-sig"))
    if source.is_file() and source.suffix.lower() == ".zip":
        with zipfile.ZipFile(source) as archive:
            hits = [name for name in archive.namelist() if name.endswith(filename)]
            if not hits:
                return {}
            return json.loads(archive.read(hits[0]).decode("utf-8-sig"))
    return {}


def find_column(
    columns: Iterable[str],
    patterns: Sequence[str],
    required: bool = False,
    label: str = "column",
) -> Optional[str]:
    columns = list(columns)
    exact = {str(col).lower(): str(col) for col in columns}
    canonical = {canonical_col_token(col): str(col) for col in columns}
    for pattern in patterns:
        if pattern.lower() in exact:
            return exact[pattern.lower()]
        token = canonical_col_token(pattern)
        if token in canonical:
            return canonical[token]
    for col in columns:
        low = str(col).lower()
        if any(str(pattern).lower() in low for pattern in patterns):
            return str(col)
    if required:
        raise KeyError(f"Could not infer {label}. Available columns: {columns}")
    return None


def normalize_score(series: pd.Series, orientation: str, transform: str) -> pd.Series:
    x = pd.to_numeric(series, errors="coerce").replace([np.inf, -np.inf], np.nan)
    orientation = orientation.lower().strip()
    transform = transform.lower().strip()
    if orientation == "negative":
        x = -x
    elif orientation == "absolute":
        x = x.abs()
    elif orientation != "positive":
        raise ValueError(f"Unknown score orientation: {orientation}")
    if x.notna().sum() == 0:
        return pd.Series(0.0, index=x.index)
    x = x.fillna(float(x.median()))
    if transform == "rank_percentile":
        if x.nunique() <= 1:
            return pd.Series(0.5, index=x.index)
        return x.rank(method="average", pct=True).astype(float)
    if transform == "minmax":
        minimum, maximum = float(x.min()), float(x.max())
        if maximum == minimum:
            return pd.Series(0.5, index=x.index)
        return ((x - minimum) / (maximum - minimum)).astype(float)
    if transform == "robust_z":
        median = float(x.median())
        mad = float((x - median).abs().median())
        if mad == 0:
            sd = float(x.std(ddof=0))
            if sd == 0 or math.isnan(sd):
                return pd.Series(0.5, index=x.index)
            z = (x - median) / sd
        else:
            z = 0.6745 * (x - median) / mad
        return (1.0 / (1.0 + np.exp(-z))).astype(float)
    if transform == "raw":
        return x.astype(float)
    raise ValueError(f"Unknown transform: {transform}")


def join_unique(series: pd.Series, max_items: int = 20) -> str:
    values = [str(value) for value in series.dropna().astype(str) if str(value).strip()]
    unique = list(dict.fromkeys(values))
    if len(unique) > max_items:
        return ";".join(unique[:max_items]) + f";...(+{len(unique) - max_items})"
    return ";".join(unique)


