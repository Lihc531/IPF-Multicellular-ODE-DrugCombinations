def load_ppi_edges(spec: Mapping[str, Any]) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    path = resolve_existing_path(spec["path"])
    raw = read_table(path).rename(columns=lambda col: clean_colname(col))
    source_col, target_col, weight_col = infer_ppi_columns(raw, spec)
    out = pd.DataFrame({
        "source_gene": raw[source_col].map(normalize_gene),
        "target_gene": raw[target_col].map(normalize_gene),
    })
    if weight_col is None:
        out["edge_weight"] = 1.0
    else:
        out["edge_weight"] = pd.to_numeric(raw[weight_col], errors="coerce")
    out = out.dropna(subset=["edge_weight"])
    out = out[(out["source_gene"] != "") & (out["target_gene"] != "")]
    out = out[out["source_gene"] != out["target_gene"]].copy()

    scale_mode = str(spec.get("weight_scale", "auto")).lower()
    original_max = float(out["edge_weight"].max()) if len(out) else float("nan")
    if scale_mode == "auto" and original_max > 10:
        out["edge_weight"] = out["edge_weight"] / 1000.0
    elif scale_mode == "0_1000":
        out["edge_weight"] = out["edge_weight"] / 1000.0
    minimum = spec.get("min_weight")
    if minimum is not None:
        out = out[out["edge_weight"] >= float(minimum)].copy()
    out = out[out["edge_weight"] > 0].copy()

    # STRING is undirected. Canonicalizing endpoints prevents reversed duplicates.
    source_values = out["source_gene"].astype(str).to_numpy()
    target_values = out["target_gene"].astype(str).to_numpy()
    source_first = source_values <= target_values
    out["source_gene"] = np.where(source_first, source_values, target_values)
    out["target_gene"] = np.where(source_first, target_values, source_values)
    out = out.groupby(["source_gene", "target_gene"], as_index=False)["edge_weight"].max()
    if out.empty:
        raise ValueError(f"PPI table became empty after filtering: {path}")
    out["ppi_name"] = str(spec["name"])

    all_genes = pd.unique(pd.concat([out["source_gene"], out["target_gene"]], ignore_index=True))
    qc = {
        "ppi_name": str(spec["name"]),
        "path": str(path),
        "sha256": file_sha256(path),
        "detected_delimiter": repr(detect_delimiter(path)),
        "source_column": source_col,
        "target_column": target_col,
        "weight_column": weight_col,
        "string_threshold": spec.get("string_threshold"),
        "n_input_rows": int(len(raw)),
        "n_edges_after_filter": int(len(out)),
        "n_unique_genes": int(len(all_genes)),
        "min_edge_weight": float(out["edge_weight"].min()),
        "mean_edge_weight": float(out["edge_weight"].mean()),
        "max_edge_weight": float(out["edge_weight"].max()),
        "original_max_weight": original_max,
    }
    return out.reset_index(drop=True), qc


def build_ppi_model(edges: pd.DataFrame, evidence_genes: Sequence[str]) -> Dict[str, Any]:
    if sp is None:
        raise RuntimeError(
            "scipy is required for full-network PPI propagation. "
            f"Import error: {SCIPY_IMPORT_ERROR}"
        )
    genes = sorted(
        set(map(str, evidence_genes))
        | set(edges["source_gene"].astype(str))
        | set(edges["target_gene"].astype(str))
    )
    index = pd.Index(genes)
    source_idx = index.get_indexer(edges["source_gene"])
    target_idx = index.get_indexer(edges["target_gene"])
    weights = edges["edge_weight"].to_numpy(dtype=float)
    rows = np.concatenate([source_idx, target_idx])
    cols = np.concatenate([target_idx, source_idx])
    data = np.concatenate([weights, weights])
    adjacency = sp.csr_matrix((data, (rows, cols)), shape=(len(genes), len(genes)), dtype=float)
    adjacency.sum_duplicates()

    weighted_degree = np.asarray(adjacency.sum(axis=1)).ravel()
    degree = np.diff(adjacency.indptr).astype(float)
    isolated = np.where(weighted_degree <= 0)[0]
    if len(isolated):
        adjacency = adjacency.tolil(copy=True)
        adjacency[isolated, isolated] = 1.0
        adjacency = adjacency.tocsr()
        weighted_degree = np.asarray(adjacency.sum(axis=1)).ravel()
    transition = sp.diags(1.0 / weighted_degree) @ adjacency

    degree_score = pd.Series(degree).rank(method="average", pct=True).to_numpy(dtype=float)
    gene_to_index = {gene: idx for idx, gene in enumerate(genes)}
    return {
        "genes": genes,
        "gene_to_index": gene_to_index,
        "transition": transition.tocsr(),
        "degree": degree,
        "weighted_degree": weighted_degree,
        "degree_score": degree_score,
        "n_isolated_evidence_genes": int(sum(gene_to_index[g] in set(isolated) for g in evidence_genes if g in gene_to_index)),
    }


def rwr_sparse(
    transition: Any,
    seed: np.ndarray,
    restart_prob: float,
    max_iter: int,
    tol: float,
) -> Tuple[np.ndarray, int, float]:
    seed = np.asarray(seed, dtype=float)
    if seed.sum() <= 0:
        seed = np.ones_like(seed) / max(len(seed), 1)
    else:
        seed = seed / seed.sum()
    current = seed.copy()
    final_delta = float("inf")
    for iteration in range(1, max_iter + 1):
        updated = restart_prob * seed + (1.0 - restart_prob) * (transition.T @ current)
        updated = np.asarray(updated).ravel()
        final_delta = float(np.linalg.norm(updated - current, ord=1))
        current = updated
        if final_delta < tol:
            return current, iteration, final_delta
    return current, max_iter, final_delta


