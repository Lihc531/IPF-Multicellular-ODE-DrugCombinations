#!/usr/bin/env python3
"""Run CellOracle TF KO/OE while retaining the original disease anchor gene.

This script requires ``targets_celloracle.csv`` generated by
04a_prepare_celloracle_tf_targets.py. The original ``targets.csv`` remains the
input of the general network-perturbation branch and is not used as a silent
fallback.

Examples
--------
python 05_run_celloracle_ko_oe.py \
  --input-dir virtual_perturbation_results/03_celloracle_inputs/main__Fibroblast \
  --output-dir virtual_perturbation_results/04_celloracle/main__Fibroblast

python 05_run_celloracle_ko_oe.py --job main__Fibroblast --check-only
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path

try:
    import anndata as ad
    import celloracle as co
    import numpy as np
    import pandas as pd
    import scanpy as sc
    from scipy import sparse
    from scipy.io import mmread
except ModuleNotFoundError as exc:
    raise SystemExit(
        f"Missing Python package: {exc.name or 'unknown'}\n"
        f"Interpreter: {sys.executable}\n"
        "Run this script inside the CellOracle conda environment."
    ) from exc


SCRIPT_ROOT = Path(__file__).resolve().parent
PIPELINE_ROOT = Path(os.getenv("VP_PIPELINE_ROOT", str(SCRIPT_ROOT))).resolve()
DEFAULT_INPUT_ROOT = Path(os.getenv("VP_OUTPUT_ROOT", str(PIPELINE_ROOT / "virtual_perturbation_results"))) / "03_celloracle_inputs"
DEFAULT_OUTPUT_ROOT = Path(os.getenv("VP_OUTPUT_ROOT", str(PIPELINE_ROOT / "virtual_perturbation_results"))) / "04_celloracle"

NON_EVALUABLE_REASONS = {"TF_below_expression_threshold"}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Run mapped upstream-TF CellOracle perturbations.")
    p.add_argument("--job", default=None, help="Prepared job name, e.g. main__Fibroblast.")
    p.add_argument("--input-dir", default=None)
    p.add_argument("--output-dir", default=None)
    p.add_argument("--list-jobs", action="store_true")
    p.add_argument("--check-only", action="store_true")
    p.add_argument("--n-jobs", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    p.add_argument("--oe-fold", type=float, default=1.5)
    p.add_argument("--n-propagation", type=int, default=3)
    p.add_argument("--run-vector-field", action="store_true")
    p.add_argument("--force-rebuild", action="store_true")
    p.add_argument("--min-expressing-cells", type=int, default=25,
                   help="Minimum TF-expressing cells required in each Control/IPF group.")
    p.add_argument(
        "--allow-original-targets",
        action="store_true",
        help="Emergency compatibility mode only; allows targets.csv when targets_celloracle.csv is absent.",
    )
    p.add_argument(
        "--allow-ineligible-targets",
        action="store_true",
        help="Exploratory only: simulate eligible targets even when canonical targets are ineligible. "
             "Formal cross-dataset validation should leave this disabled.",
    )
    return p.parse_args()


def resolve_paths(args: argparse.Namespace) -> tuple[Path, Path]:
    if args.input_dir:
        input_dir = Path(args.input_dir).expanduser()
    elif args.job:
        input_dir = DEFAULT_INPUT_ROOT / args.job
    else:
        raise SystemExit("Provide --job or --input-dir.")
    if args.output_dir:
        output_dir = Path(args.output_dir).expanduser()
    elif args.job:
        output_dir = DEFAULT_OUTPUT_ROOT / args.job
    else:
        output_dir = DEFAULT_OUTPUT_ROOT / input_dir.name
    return input_dir.resolve(), output_dir.resolve()


def list_jobs() -> list[str]:
    if not DEFAULT_INPUT_ROOT.is_dir():
        return []
    required = {"counts_genes_by_cells.mtx", "genes.tsv", "barcodes.tsv", "cell_metadata.csv"}
    return [
        p.name for p in sorted(DEFAULT_INPUT_ROOT.iterdir())
        if p.is_dir() and required.issubset({q.name for q in p.iterdir()})
    ]


def file_digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()




def combined_digest(paths: list[Path]) -> str:
    h = hashlib.sha256()
    for path in paths:
        h.update(path.name.encode("utf-8"))
        h.update(file_digest(path).encode("ascii"))
    return h.hexdigest()

def validate_input_dir(input_dir: Path, allow_original: bool) -> Path:
    required = ["counts_genes_by_cells.mtx", "genes.tsv", "barcodes.tsv", "cell_metadata.csv"]
    if not input_dir.is_dir():
        raise FileNotFoundError(f"Input directory does not exist: {input_dir}")
    missing = [x for x in required if not (input_dir / x).is_file()]
    if missing:
        raise FileNotFoundError(f"Incomplete input directory {input_dir}; missing: {', '.join(missing)}")
    mapped = input_dir / "targets_celloracle.csv"
    if mapped.is_file():
        return mapped
    original = input_dir / "targets.csv"
    if allow_original and original.is_file():
        print("WARNING: using targets.csv because --allow-original-targets was supplied.")
        return original
    raise FileNotFoundError(
        f"Missing mapped TF target table: {mapped}\n"
        "Run: python 04a_prepare_celloracle_tf_targets.py --apply\n"
        "The original targets.csv is intentionally not used because it may contain non-TF anchor genes."
    )


def normalize_targets(targets: pd.DataFrame, source: Path) -> pd.DataFrame:
    if targets.empty:
        raise ValueError(f"Target table is empty: {source}")
    targets = targets.copy()
    if "tf_gene" not in targets.columns:
        if "gene" not in targets.columns:
            raise ValueError(f"Target table must contain tf_gene or gene: {source}")
        targets["tf_gene"] = targets["gene"]
    if "anchor_gene" not in targets.columns:
        targets["anchor_gene"] = targets.get("gene", targets["tf_gene"])
    if "celltype" not in targets.columns:
        raise ValueError(f"Target table must contain celltype: {source}")
    targets["tf_gene"] = targets["tf_gene"].astype(str).str.strip()
    targets["anchor_gene"] = targets["anchor_gene"].astype(str).str.strip()
    targets["celltype"] = targets["celltype"].astype(str).str.strip()
    targets["gene"] = targets["tf_gene"]
    targets = targets[(targets["tf_gene"] != "") & (targets["anchor_gene"] != "")]
    return targets.drop_duplicates(["celltype", "anchor_gene", "tf_gene"])


def read_input(input_dir: Path, target_path: Path) -> tuple[ad.AnnData, pd.DataFrame]:
    counts = mmread(input_dir / "counts_genes_by_cells.mtx").tocsr()
    genes = pd.read_csv(input_dir / "genes.tsv", sep="\t", header=None)[0].astype(str).tolist()
    cells = pd.read_csv(input_dir / "barcodes.tsv", sep="\t", header=None)[0].astype(str).tolist()
    meta = pd.read_csv(input_dir / "cell_metadata.csv")
    targets = normalize_targets(pd.read_csv(target_path), target_path)
    if counts.shape != (len(genes), len(cells)):
        raise ValueError(f"Matrix shape {counts.shape} does not match {len(genes)} genes x {len(cells)} cells.")
    if "cell_id" not in meta.columns:
        raise ValueError("cell_metadata.csv must contain cell_id.")
    if "disease_for_perturbation" not in meta.columns:
        raise ValueError("cell_metadata.csv must contain disease_for_perturbation.")
    meta = meta.set_index("cell_id")
    missing_cells = [x for x in cells if x not in meta.index]
    if missing_cells:
        raise ValueError(f"Metadata is missing {len(missing_cells)} matrix barcodes.")
    meta = meta.loc[cells]
    if len(set(genes)) != len(genes):
        raise ValueError("Gene symbols are duplicated. Resolve duplicates before CellOracle.")
    adata = ad.AnnData(X=counts.T.tocsr(), obs=meta.copy(), var=pd.DataFrame(index=genes))
    adata.layers["raw_count"] = adata.X.copy()
    return adata, targets


def tf_space_from_base_grn(base_grn: pd.DataFrame) -> set[str]:
    return set(map(str, base_grn.columns)) - {"peak_id", "gene_short_name"}


def eligibility_report(
    targets: pd.DataFrame, adata: ad.AnnData, tf_space: set[str], min_expressing_cells: int
) -> pd.DataFrame:
    report = targets.copy()
    genes = pd.Index(adata.var_names.astype(str))
    gene_set = set(genes)
    report["in_celloracle_tf_space"] = report["tf_gene"].isin(tf_space)
    report["in_expression_matrix"] = report["tf_gene"].isin(gene_set)
    report["anchor_in_expression_matrix"] = report["anchor_gene"].isin(gene_set)

    raw = adata.layers["raw_count"]
    conditions = adata.obs["disease_for_perturbation"].astype(str).to_numpy()
    gene_index = {g: i for i, g in enumerate(genes)}
    for condition in ("Control", "IPF"):
        mask = conditions == condition
        values = []
        for tf in report["tf_gene"].astype(str):
            idx = gene_index.get(tf)
            if idx is None or not mask.any():
                values.append(0)
                continue
            column = raw[mask, idx]
            n_expr = int(column.getnnz()) if sparse.issparse(column) else int(np.sum(np.asarray(column) > 0))
            values.append(n_expr)
        report[f"{condition}_tf_n_expr"] = values
    report["min_tf_n_expr"] = report[["Control_tf_n_expr", "IPF_tf_n_expr"]].min(axis=1)
    report["expression_eligible"] = report["min_tf_n_expr"] >= int(min_expressing_cells)
    report["eligible"] = (
        report["in_celloracle_tf_space"]
        & report["in_expression_matrix"]
        & report["anchor_in_expression_matrix"]
        & report["expression_eligible"]
    )
    report["reason"] = np.select(
        [
            ~report["in_celloracle_tf_space"],
            report["in_celloracle_tf_space"] & ~report["in_expression_matrix"],
            report["in_celloracle_tf_space"] & report["in_expression_matrix"] & ~report["anchor_in_expression_matrix"],
            report["in_celloracle_tf_space"] & report["in_expression_matrix"]
            & report["anchor_in_expression_matrix"] & ~report["expression_eligible"],
        ],
        [
            "not_in_CellOracle_TF_space",
            "TF_not_in_expression_matrix",
            "anchor_not_in_expression_matrix",
            "TF_below_expression_threshold",
        ],
        default="eligible",
    )
    return report


def preprocess_for_embedding(adata: ad.AnnData) -> None:
    if adata.n_obs < 12 or adata.n_vars < 12:
        raise ValueError(f"CellOracle input is too small: {adata.n_obs} cells, {adata.n_vars} genes.")
    adata.X = adata.layers["raw_count"].copy()
    sc.pp.normalize_total(adata, target_sum=1e4)
    sc.pp.log1p(adata)
    n_comps = max(2, min(50, adata.n_vars - 1, adata.n_obs - 1))
    sc.tl.pca(adata, n_comps=n_comps, svd_solver="arpack")
    n_neighbors = max(2, min(30, adata.n_obs - 1))
    sc.pp.neighbors(adata, n_neighbors=n_neighbors, n_pcs=min(30, n_comps))
    sc.tl.umap(adata, random_state=123)
    try:
        sc.tl.leiden(adata, resolution=0.6, key_added="state_cluster", random_state=123)
    except Exception as exc:
        print(f"Leiden clustering was unavailable ({exc}); using disease labels for display.")
        adata.obs["state_cluster"] = adata.obs["disease_for_perturbation"].astype(str)
    adata.obs["grn_cluster"] = adata.obs["disease_for_perturbation"].astype(str)


def assert_loaded_model_matches_input(oracle, adata: ad.AnnData) -> None:
    model_genes = pd.Index(oracle.adata.var_names.astype(str))
    model_cells = pd.Index(oracle.adata.obs_names.astype(str))
    input_genes = pd.Index(adata.var_names.astype(str))
    input_cells = pd.Index(adata.obs_names.astype(str))
    if not model_genes.equals(input_genes) or not model_cells.equals(input_cells):
        raise RuntimeError(
            "Existing fitted CellOracle model does not match the current input genes/cells.\n"
            "The CellOracle inputs were probably re-exported. Re-run with --force-rebuild."
        )


def build_or_load_oracle(adata: ad.AnnData, out_dir: Path, n_jobs: int, base_grn: pd.DataFrame):
    oracle_path = out_dir / "fitted.celloracle.oracle"
    links_path = out_dir / "links.celloracle.links"
    if oracle_path.exists() != links_path.exists():
        raise RuntimeError(
            "Only one of fitted.celloracle.oracle / links.celloracle.links exists. "
            "Remove the partial output or use --force-rebuild."
        )
    if oracle_path.exists() and links_path.exists():
        print("Loading existing Oracle and Links objects...")
        oracle = co.load_hdf5(str(oracle_path))
        links = co.load_hdf5(str(links_path))
        assert_loaded_model_matches_input(oracle, adata)
        return oracle, links

    adata.X = adata.layers["raw_count"].copy()
    oracle = co.Oracle()
    oracle.import_anndata_as_raw_count(
        adata=adata,
        cluster_column_name="grn_cluster",
        embedding_name="X_umap",
    )
    oracle.import_TF_data(TF_info_matrix=base_grn)
    oracle.perform_PCA()
    n_cells = oracle.adata.shape[0]
    n_comps = max(2, min(30, oracle.adata.shape[1] - 1, oracle.adata.shape[0] - 1))
    k = max(2, min(100, int(0.025 * n_cells)))
    oracle.knn_imputation(
        n_pca_dims=n_comps,
        k=k,
        balanced=True,
        b_sight=max(k + 1, k * 8),
        b_maxl=max(k + 1, k * 4),
        n_jobs=n_jobs,
    )
    links = oracle.get_links(
        cluster_name_for_GRN_unit="grn_cluster",
        alpha=10,
        bagging_number=10,
        verbose_level=1,
        n_jobs=n_jobs,
    )
    links.filter_links(p=0.001, weight="coef_abs", threshold_number=2000)
    oracle.get_cluster_specific_TFdict_from_Links(links_object=links)
    oracle.fit_GRN_for_simulation(alpha=10, use_cluster_specific_TFdict=True, verbose_level=1)
    oracle.to_hdf5(str(oracle_path))
    links.to_hdf5(str(links_path))
    return oracle, links


def get_axis_weights(input_dir: Path, genes: pd.Index) -> pd.Series:
    path = input_dir / "axis_gene_weights.csv"
    if not path.is_file():
        return pd.Series(dtype=float)
    w = pd.read_csv(path)
    if not {"gene", "spearman_axis"}.issubset(w.columns):
        return pd.Series(dtype=float)
    w["spearman_axis"] = pd.to_numeric(w["spearman_axis"], errors="coerce")
    w = w.dropna(subset=["spearman_axis"]).drop_duplicates("gene")
    s = w.set_index("gene")["spearman_axis"].reindex(genes).dropna()
    denom = float(np.abs(s).sum())
    return s / denom if denom > 0 else s


def simulation_delta(oracle, gene: str, value: float, n_propagation: int) -> np.ndarray:
    oracle.simulate_shift(
        perturb_condition={gene: float(value)},
        GRN_unit="cluster",
        n_propagation=n_propagation,
        clip_delta_X=True,
    )
    simulated = oracle.adata.layers["simulated_count"]
    baseline = oracle.adata.layers["imputed_count"]
    if sparse.issparse(simulated):
        simulated = simulated.toarray()
    if sparse.issparse(baseline):
        baseline = baseline.toarray()
    return np.asarray(simulated) - np.asarray(baseline)


def anchor_link_coefficient(links, condition: str, tf_gene: str, anchor_gene: str) -> float:
    dictionaries = []
    if hasattr(links, "filtered_links") and isinstance(links.filtered_links, dict):
        dictionaries.append(links.filtered_links)
    if hasattr(links, "links_dict") and isinstance(links.links_dict, dict):
        dictionaries.append(links.links_dict)
    for d in dictionaries:
        frame = d.get(condition)
        if frame is None or not isinstance(frame, pd.DataFrame):
            continue
        if not {"source", "target"}.issubset(frame.columns):
            continue
        hit = frame[
            frame["source"].astype(str).eq(tf_gene)
            & frame["target"].astype(str).eq(anchor_gene)
        ]
        if hit.empty:
            continue
        coef_col = "coef_mean" if "coef_mean" in hit.columns else ("coef" if "coef" in hit.columns else None)
        if coef_col:
            vals = pd.to_numeric(hit[coef_col], errors="coerce").dropna()
            if len(vals):
                return float(vals.iloc[np.argmax(np.abs(vals.to_numpy()))])
    return float("nan")


def summarize_delta(
    delta: np.ndarray,
    oracle,
    links,
    dataset: str,
    celltype: str,
    tf_gene: str,
    anchor_gene: str,
    perturbation: str,
    perturb_value: float,
    axis_weights: pd.Series,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    genes = pd.Index(oracle.adata.var_names.astype(str))
    obs = oracle.adata.obs
    anchor_idx = genes.get_indexer([anchor_gene])[0] if anchor_gene in genes else -1
    gene_rows: list[pd.DataFrame] = []
    summary_rows: list[dict[str, object]] = []
    for condition in sorted(obs["disease_for_perturbation"].astype(str).unique()):
        mask = obs["disease_for_perturbation"].astype(str).to_numpy() == condition
        mean_delta = np.asarray(delta[mask].mean(axis=0)).ravel()
        frame = pd.DataFrame(
            {
                "dataset": dataset,
                "celltype": celltype,
                "condition": condition,
                "anchor_gene": anchor_gene,
                "tf_gene": tf_gene,
                "target_gene": tf_gene,
                "perturbation": perturbation,
                "perturb_value": perturb_value,
                "gene": genes,
                "mean_delta": mean_delta,
                "abs_mean_delta": np.abs(mean_delta),
            }
        )
        gene_rows.append(frame)
        common = axis_weights.index.intersection(genes)
        if len(common):
            idx = genes.get_indexer(common)
            axis_score = float(np.dot(mean_delta[idx], axis_weights.loc[common].to_numpy()))
        else:
            axis_score = float("nan")
        anchor_delta = float(mean_delta[anchor_idx]) if anchor_idx >= 0 else float("nan")
        summary_rows.append(
            {
                "dataset": dataset,
                "celltype": celltype,
                "condition": condition,
                "anchor_gene": anchor_gene,
                "tf_gene": tf_gene,
                "target_gene": tf_gene,
                "perturbation": perturbation,
                "perturb_value": perturb_value,
                "axis_shift_score": axis_score,
                "anchor_mean_delta": anchor_delta,
                "anchor_abs_delta": abs(anchor_delta) if np.isfinite(anchor_delta) else float("nan"),
                "anchor_present": anchor_idx >= 0,
                "anchor_link_coef": anchor_link_coefficient(links, condition, tf_gene, anchor_gene),
                "n_cells": int(mask.sum()),
                "mean_abs_delta": float(np.mean(np.abs(mean_delta))),
            }
        )
    return pd.concat(gene_rows, ignore_index=True), pd.DataFrame(summary_rows)


def write_metadata(out_dir: Path, payload: dict[str, object]) -> None:
    with (out_dir / "run_metadata.json").open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)


def main() -> None:
    args = parse_args()
    if args.list_jobs:
        print(f"Input root: {DEFAULT_INPUT_ROOT}")
        for job in list_jobs():
            print(job)
        return

    input_dir, out_dir = resolve_paths(args)
    target_path = validate_input_dir(input_dir, args.allow_original_targets)
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"Python executable: {sys.executable}")
    print(f"CellOracle version: {co.__version__}")
    print(f"Input directory: {input_dir}")
    print(f"Output directory: {out_dir}")
    print(f"Target table: {target_path}")

    adata, targets = read_input(input_dir, target_path)
    base_grn = co.data.load_human_promoter_base_GRN()
    tf_space = tf_space_from_base_grn(base_grn)
    if args.min_expressing_cells < 1:
        raise SystemExit("--min-expressing-cells must be >= 1.")
    report = eligibility_report(targets, adata, tf_space, args.min_expressing_cells)
    report.to_csv(out_dir / "target_eligibility_report.csv", index=False)
    skipped = report[~report["eligible"]].copy()
    skipped.to_csv(out_dir / "skipped_targets.csv", index=False)

    # Low expression is a scientifically valid "not evaluable in this dataset"
    # state, not a failed job. Other eligibility failures remain hard blockers
    # because they usually indicate incompatible inputs or TF-space problems.
    non_evaluable = skipped[skipped["reason"].isin(NON_EVALUABLE_REASONS)].copy()
    hard_ineligible = skipped[~skipped["reason"].isin(NON_EVALUABLE_REASONS)].copy()
    non_evaluable.to_csv(out_dir / "non_evaluable_targets.csv", index=False)
    hard_ineligible.to_csv(out_dir / "hard_ineligible_targets.csv", index=False)
    eligible = report[report["eligible"]].copy()

    observed_conditions = set(adata.obs["disease_for_perturbation"].astype(str))
    missing_conditions = sorted({"Control", "IPF"}.difference(observed_conditions))

    dataset = str(targets["dataset"].iloc[0]) if "dataset" in targets.columns else input_dir.name.split("__", 1)[0]
    celltype = str(targets["celltype"].iloc[0])
    input_signature = combined_digest([
        input_dir / "genes.tsv",
        input_dir / "barcodes.tsv",
        input_dir / "cell_metadata.csv",
        target_path,
    ])
    metadata_base = {
        "celloracle_version": co.__version__,
        "dataset": dataset,
        "celltype": celltype,
        "n_cells": int(adata.n_obs),
        "n_genes": int(adata.n_vars),
        "n_targets_requested": int(len(targets)),
        "n_tf_targets_eligible": int(len(eligible)),
        "target_table": str(target_path),
        "target_table_sha256": file_digest(target_path),
        "input_signature_sha256": input_signature,
        "oe_fold": args.oe_fold,
        "n_propagation": args.n_propagation,
        "min_expressing_cells": args.min_expressing_cells,
        "required_conditions": ["Control", "IPF"],
        "observed_conditions": sorted(observed_conditions),
        "n_ineligible_targets": int(len(skipped)),
        "n_non_evaluable_targets": int(len(non_evaluable)),
        "n_hard_ineligible_targets": int(len(hard_ineligible)),
        "non_evaluable_reasons": sorted(set(non_evaluable["reason"].astype(str))) if len(non_evaluable) else [],
    }
    if missing_conditions:
        write_metadata(out_dir, {**metadata_base, "status": "stopped_missing_required_conditions", "missing_conditions": missing_conditions})
        raise SystemExit(
            "CellOracle input does not contain both required disease groups. "
            f"Missing conditions: {missing_conditions}"
        )
    if len(hard_ineligible) and not args.allow_ineligible_targets:
        write_metadata(out_dir, {**metadata_base, "status": "stopped_hard_ineligible_tf_targets"})
        raise SystemExit(
            f"{len(hard_ineligible)} canonical anchor-TF targets have hard eligibility failures "
            f"in {dataset}__{celltype}. Review {out_dir / 'hard_ineligible_targets.csv'}. "
            "Only low-expression targets may be recorded as formally non-evaluable."
        )

    if len(non_evaluable):
        print(
            f"{len(non_evaluable)} canonical anchor-TF target(s) are formally non-evaluable "
            f"in {dataset}__{celltype} because expression is below the threshold. "
            f"They will be excluded from the evaluable-test denominator; review "
            f"{out_dir / 'non_evaluable_targets.csv'}."
        )

    if args.check_only:
        status = "check_passed_with_non_evaluable_targets" if len(non_evaluable) else "check_passed"
        write_metadata(out_dir, {**metadata_base, "status": status})
        if eligible.empty and len(non_evaluable):
            print("Checks passed: no evaluable targets remain in this job; no model fitting is required.")
        else:
            print("Input and TF-target checks passed. No model was fitted.")
        return

    if eligible.empty:
        # A job containing only low-expression canonical targets is complete in
        # the formal sense: it has zero evaluable tests and an auditable
        # non-evaluable manifest. Write empty aggregate outputs with stable
        # schemas so downstream readers do not fail on missing files.
        pd.DataFrame(columns=[
            "dataset", "celltype", "condition", "anchor_gene", "tf_gene", "target_gene",
            "perturbation", "perturb_value", "gene", "mean_delta", "abs_mean_delta",
        ]).to_csv(out_dir / "celloracle_gene_deltas.csv.gz", index=False, compression="gzip")
        pd.DataFrame(columns=[
            "dataset", "celltype", "condition", "anchor_gene", "tf_gene", "target_gene",
            "perturbation", "perturb_value", "axis_shift_score", "anchor_mean_delta",
            "anchor_abs_delta", "anchor_present", "anchor_link_coef", "n_cells", "mean_abs_delta",
        ]).to_csv(out_dir / "celloracle_perturbation_summary.csv", index=False)

        rows = []
        for target in non_evaluable[["anchor_gene", "tf_gene", "reason"]].drop_duplicates().itertuples(index=False):
            for condition in ("Control", "IPF"):
                for perturbation in ("KO", "OE"):
                    rows.append({
                        "dataset": dataset,
                        "celltype": celltype,
                        "condition": condition,
                        "anchor_gene": str(target.anchor_gene),
                        "tf_gene": str(target.tf_gene),
                        "perturbation": perturbation,
                        "evaluable": False,
                        "non_evaluable_reason": str(target.reason),
                        "summary_present": False,
                        "gene_delta_present": False,
                        "test_complete": False,
                        "formal_requirement_satisfied": True,
                    })
        pd.DataFrame(rows).to_csv(out_dir / "celloracle_output_completeness.csv", index=False)
        write_metadata(
            out_dir,
            {
                **metadata_base,
                "status": "completed_no_evaluable_targets",
                "n_tf_targets_simulated": 0,
                "n_expected_canonical_tests": int(len(rows)),
                "n_evaluable_tests": 0,
                "n_non_evaluable_tests": int(len(rows)),
                "n_completed_evaluable_tests": 0,
                "n_runtime_skipped_targets": 0,
                "axis_weight_genes_used": 0,
            },
        )
        print("Completed with zero evaluable targets; non-evaluable targets were recorded explicitly.")
        return

    preprocess_for_embedding(adata)
    oracle_file = out_dir / "fitted.celloracle.oracle"
    links_file = out_dir / "links.celloracle.links"
    if args.force_rebuild:
        for p in (oracle_file, links_file):
            if p.exists():
                p.unlink()
    oracle, links = build_or_load_oracle(adata, out_dir, args.n_jobs, base_grn)
    axis_weights = get_axis_weights(input_dir, pd.Index(oracle.adata.var_names.astype(str)))

    imputed = oracle.adata.layers["imputed_count"]
    if sparse.issparse(imputed):
        imputed = imputed.toarray()
    imputed = np.asarray(imputed)
    all_gene_results: list[pd.DataFrame] = []
    all_summaries: list[pd.DataFrame] = []
    runtime_skips: list[dict[str, object]] = []
    runtime_skip_path = out_dir / "runtime_skipped_targets.csv"
    if runtime_skip_path.exists():
        runtime_skip_path.unlink()

    for row in eligible.itertuples(index=False):
        tf_gene = str(row.tf_gene)
        anchor_gene = str(row.anchor_gene)
        j = oracle.adata.var_names.get_loc(tf_gene)
        expr = imputed[:, j]
        max_expr = float(np.max(expr))
        if max_expr <= 0:
            runtime_skips.append({"celltype": celltype, "anchor_gene": anchor_gene, "tf_gene": tf_gene, "reason": "zero_imputed_expression"})
            continue
        q90 = float(np.quantile(expr, 0.90))
        oe_value = min(2.0 * max_expr, max(max_expr, q90) * args.oe_fold)
        for perturbation, value in (("KO", 0.0), ("OE", oe_value)):
            delta = simulation_delta(oracle, tf_gene, value, args.n_propagation)
            gene_df, summary_df = summarize_delta(
                delta, oracle, links, dataset, celltype, tf_gene, anchor_gene,
                perturbation, value, axis_weights,
            )
            all_gene_results.append(gene_df)
            all_summaries.append(summary_df)
            if args.run_vector_field:
                oracle.estimate_transition_prob(
                    n_neighbors=min(200, oracle.adata.n_obs - 1),
                    knn_random=True,
                    sampled_fraction=1,
                )
                oracle.calculate_embedding_shift(sigma_corr=0.05)
                np.savez_compressed(
                    out_dir / f"{anchor_gene}__{tf_gene}__{perturbation}__vector_field.npz",
                    embedding=np.asarray(oracle.adata.obsm["X_umap"]),
                    delta_embedding=np.asarray(oracle.delta_embedding),
                )

    if runtime_skips:
        pd.DataFrame(runtime_skips).to_csv(runtime_skip_path, index=False)
    if not all_gene_results:
        pd.DataFrame(columns=[
            "dataset", "celltype", "condition", "anchor_gene", "tf_gene", "target_gene",
            "perturbation", "perturb_value", "gene", "mean_delta", "abs_mean_delta",
        ]).to_csv(out_dir / "celloracle_gene_deltas.csv.gz", index=False, compression="gzip")
        pd.DataFrame(columns=[
            "dataset", "celltype", "condition", "anchor_gene", "tf_gene", "target_gene",
            "perturbation", "perturb_value", "axis_shift_score", "anchor_mean_delta",
            "anchor_abs_delta", "anchor_present", "anchor_link_coef", "n_cells", "mean_abs_delta",
        ]).to_csv(out_dir / "celloracle_perturbation_summary.csv", index=False)
        write_metadata(out_dir, {**metadata_base, "status": "completed_without_simulatable_targets"})
        raise SystemExit("Eligible TFs were found but none had positive imputed expression.")

    gene_results = pd.concat(all_gene_results, ignore_index=True)
    summaries = pd.concat(all_summaries, ignore_index=True)
    gene_results.to_csv(out_dir / "celloracle_gene_deltas.csv.gz", index=False, compression="gzip")
    summaries.to_csv(out_dir / "celloracle_perturbation_summary.csv", index=False)

    key_cols = ["dataset", "celltype", "condition", "anchor_gene", "tf_gene", "perturbation"]
    expected_rows = []
    report_lookup = (
        report[["anchor_gene", "tf_gene", "eligible", "reason"]]
        .drop_duplicates(["anchor_gene", "tf_gene"])
        .set_index(["anchor_gene", "tf_gene"])
    )
    for target in report[["anchor_gene", "tf_gene"]].drop_duplicates().itertuples(index=False):
        row = report_lookup.loc[(target.anchor_gene, target.tf_gene)]
        is_evaluable = bool(row["eligible"])
        reason = "" if is_evaluable else str(row["reason"])
        for condition in ("Control", "IPF"):
            for perturbation in ("KO", "OE"):
                expected_rows.append({
                    "dataset": dataset,
                    "celltype": celltype,
                    "condition": condition,
                    "anchor_gene": str(target.anchor_gene),
                    "tf_gene": str(target.tf_gene),
                    "perturbation": perturbation,
                    "evaluable": is_evaluable,
                    "non_evaluable_reason": reason,
                })
    completeness = pd.DataFrame(expected_rows)
    summary_keys = summaries[key_cols].drop_duplicates().copy()
    gene_keys = gene_results[key_cols].drop_duplicates().copy()
    completeness = completeness.merge(
        summary_keys.assign(summary_present=True), on=key_cols, how="left"
    ).merge(
        gene_keys.assign(gene_delta_present=True), on=key_cols, how="left"
    )
    completeness["summary_present"] = completeness["summary_present"].fillna(False).astype(bool)
    completeness["gene_delta_present"] = completeness["gene_delta_present"].fillna(False).astype(bool)
    completeness["test_complete"] = completeness["summary_present"] & completeness["gene_delta_present"]
    completeness["formal_requirement_satisfied"] = (~completeness["evaluable"]) | completeness["test_complete"]
    completeness.to_csv(out_dir / "celloracle_output_completeness.csv", index=False)

    evaluable_mask = completeness["evaluable"].astype(bool)
    n_canonical = int(len(completeness))
    n_evaluable = int(evaluable_mask.sum())
    n_non_evaluable = int((~evaluable_mask).sum())
    n_complete = int(completeness.loc[evaluable_mask, "test_complete"].sum())
    status = (
        "completed_with_perturbation_results"
        if n_complete == n_evaluable and not runtime_skips
        else "completed_with_missing_target_tests"
    )
    write_metadata(
        out_dir,
        {
            **metadata_base,
            "status": status,
            "n_tf_targets_simulated": int(summaries[["anchor_gene", "tf_gene"]].drop_duplicates().shape[0]),
            "n_summary_rows": int(len(summaries)),
            "n_expected_canonical_tests": n_canonical,
            "n_evaluable_tests": n_evaluable,
            "n_non_evaluable_tests": n_non_evaluable,
            "n_completed_evaluable_tests": n_complete,
            # Backward-compatible aliases refer to evaluable tests.
            "n_expected_tests": n_evaluable,
            "n_completed_tests": n_complete,
            "n_runtime_skipped_targets": int(len(runtime_skips)),
            "axis_weight_genes_used": int(len(axis_weights)),
        },
    )
    if status != "completed_with_perturbation_results":
        raise SystemExit(
            f"CellOracle output is incomplete: {n_complete}/{n_evaluable} evaluable tests "
            f"({n_non_evaluable} additional canonical tests are non-evaluable). "
            f"Review {out_dir / 'celloracle_output_completeness.csv'} and runtime_skipped_targets.csv."
        )
    print(f"Completed. Summary: {out_dir / 'celloracle_perturbation_summary.csv'}")


if __name__ == "__main__":
    main()
